/// `value` inside double quotes for a POSIX shell (`$`, `` ` ``, `"` and `\`
/// escaped).
pub(crate) fn sh_double_quoted(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for c in value.chars() {
        if matches!(c, '$' | '`' | '"' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

