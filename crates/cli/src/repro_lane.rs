// ── tools, findings, eligibility ────────────────────────────────────────────

/// The command asking whether a finding is eligible.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Tool {
    Capsule,
    Cartography,
    EnvCapsule,
}

impl Tool {
    pub(crate) fn command(self) -> &'static str {
        match self {
            Tool::Capsule => "bhf capsule",
            Tool::Cartography => "bhf cartography",
            Tool::EnvCapsule => "bhf env-capsule",
        }
    }

    /// What the tool does to a finding.
    pub(crate) fn verb(self) -> &'static str {
        match self {
            Tool::Capsule => "package",
            Tool::Cartography => "map",
            Tool::EnvCapsule => "capture",
        }
    }
}

/// One finding record read from the work dir.
#[derive(Debug, Clone)]
pub(crate) struct FindingRecord {
    pub(crate) id: String,
    pub(crate) dir: PathBuf,
    pub(crate) raw: Value,
}

/// A finding a tool can work on, with everything the tool needs located.
pub(crate) struct Eligible {
    pub(crate) lane: &'static dyn Lane,
    pub(crate) harness_id: String,
    /// The harness source dir (always set for [`Tool::Capsule`]).
    pub(crate) harness_dir: Option<PathBuf>,
    /// The built harness executable (always set for [`Tool::Cartography`] and
    /// [`Tool::EnvCapsule`]).
    pub(crate) binary: Option<PathBuf>,
    /// The finding's crash inputs, minimized first.
    pub(crate) inputs: Vec<PathBuf>,
}

/// Why a tool does not work on a finding.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Refusal {
    /// No finding has the requested id.
    NotFound { id: String, findings_dir: PathBuf },
    /// The finding dir exists but its `finding.json` cannot be read.
    Unreadable { path: PathBuf },
    /// Not a runtime sanitizer crash (`classification` other than `unhandled`).
    NotACrash { classification: String },
    /// `finding.json` names no harness.
    NoHarness,
    /// The recorded harness id is not a safe single path segment.
    InvalidHarnessId { harness_id: String },
    /// Neither `min_testcase.bin` nor `testcase.bin` is in the finding dir.
    NoInput,
    /// No harness dir with this id exists in the work dir.
    HarnessNotFound {
        harness_id: String,
        searched: Vec<PathBuf>,
    },
    /// The harness dir exists, but nothing says what language it is.
    UnknownLanguage {
        harness_id: String,
        harness_dir: PathBuf,
    },
    /// The harness's language has no lane.
    UnsupportedLane {
        harness_id: String,
        language: String,
    },
    /// The lane cannot rebuild this harness dir.
    IncompleteHarness {
        harness_id: String,
        language: String,
        harness_dir: PathBuf,
        problem: String,
    },
    /// The harness was never built (no executable to replay).
    NotBuilt {
        harness_id: String,
        language: String,
    },
    /// The lane exists, but the tool does not work on its findings.
    ToolNotForLane {
        harness_id: String,
        language: String,
        reason: String,
    },
}

impl Refusal {
    /// One sentence for the operator: why `tool` does not take this finding.
    pub(crate) fn reason(&self, tool: Tool) -> String {
        let command = tool.command();
        match self {
            Refusal::NotFound { id, findings_dir } => {
                format!("no finding with id {id} in {}", findings_dir.display())
            }
            Refusal::Unreadable { path } => {
                format!("{} is missing or is not valid JSON", path.display())
            }
            Refusal::NotACrash { classification } if classification == "oracle" => format!(
                "it is an oracle finding (a behavioral check fired, not a sanitizer crash); \
                 {command} works from a sanitizer crash"
            ),
            Refusal::NotACrash { classification } if classification.is_empty() => format!(
                "finding.json records no classification; {command} works from a runtime \
                 sanitizer crash (`unhandled`)"
            ),
            Refusal::NotACrash { classification } => format!(
                "its classification is `{classification}`, not a runtime sanitizer crash \
                 (`unhandled`); {command} works from a crash input"
            ),
            Refusal::NoHarness => {
                "finding.json records no harness_id, so there is no harness to rebuild or replay"
                    .to_owned()
            }
            Refusal::InvalidHarnessId { harness_id } => {
                format!("its harness id {harness_id:?} is not a single safe path segment")
            }
            Refusal::NoInput => {
                "the finding dir has neither min_testcase.bin nor testcase.bin".to_owned()
            }
            Refusal::HarnessNotFound {
                harness_id,
                searched,
            } => {
                // Every candidate is `<work>/<layout dir>/<id>`.
                let work = searched.first().and_then(|p| p.parent()?.parent());
                let layouts: Vec<String> = searched
                    .iter()
                    .filter_map(|p| p.parent()?.file_name())
                    .map(|name| format!("{}/", name.to_string_lossy()))
                    .collect();
                match work {
                    Some(work) => format!(
                        "harness {harness_id} was not found in {} under {}",
                        layouts.join(", "),
                        work.display()
                    ),
                    None => format!("harness {harness_id} was not found"),
                }
            }
            Refusal::UnknownLanguage {
                harness_id,
                harness_dir,
            } => format!(
                "cannot tell the language of harness {harness_id}: {} records none, its id \
                 carries no language prefix, and the dir holds no harness driver bhf generates",
                harness_dir.join(GENERATION_METADATA).display()
            ),
            Refusal::UnsupportedLane {
                harness_id,
                language,
            } => format!(
                "harness {harness_id} is {} {} harness; {command} supports {} harnesses only",
                article(&language_name(language)),
                language_name(language),
                supported_language_names_for(tool)
            ),
            Refusal::ToolNotForLane {
                harness_id,
                language,
                reason,
            } => format!(
                "harness {harness_id} is {} {} harness, and {reason}",
                article(&language_name(language)),
                language_name(language),
            ),
            Refusal::IncompleteHarness {
                harness_id,
                language,
                harness_dir,
                problem,
            } => format!(
                "{} harness {harness_id} in {} cannot be rebuilt: {problem}",
                language_name(language),
                harness_dir.display()
            ),
            Refusal::NotBuilt {
                harness_id,
                language,
            } => format!(
                "{} harness {harness_id} has no built executable (no `main` in \
                 build/{harness_id}/ or the harness dir); build it with `bhf build <work-dir> \
                 --harness {harness_id}`",
                language_name(language)
            ),
        }
    }
}

fn article(name: &str) -> &'static str {
    match name.chars().next() {
        Some('A' | 'E' | 'I' | 'O' | 'U') => "an",
        _ => "a",
    }
}

/// A refused finding: its id, why, and a command that reproduces it anyway.
pub(crate) struct Refused {
    pub(crate) id: String,
    pub(crate) refusal: Refusal,
    pub(crate) alternative: Option<String>,
}

/// The findings a tool takes and the ones it refuses.
pub(crate) struct Selection {
    pub(crate) eligible: Vec<(FindingRecord, Eligible)>,
    pub(crate) refused: Vec<Refused>,
    /// Runtime findings considered (crashes and oracle hits). Zero means the
    /// work dir has nothing a reproduction command could act on.
    pub(crate) considered: usize,
}

/// The crash inputs in a finding dir, minimized first.
pub(crate) fn crash_inputs(finding_dir: &Path) -> Vec<PathBuf> {
    ["min_testcase.bin", "testcase.bin"]
        .iter()
        .map(|name| finding_dir.join(name))
        .filter(|path| path.is_file())
        .collect()
}

/// Select the findings `tool` works on: `only` alone when given (refused with
/// [`Refusal::NotFound`] when no finding has that id), else every runtime
/// finding (crashes and oracle hits; static rows are not reproduction targets).
pub(crate) fn select(work_dir: &Path, only: Option<&str>, tool: Tool) -> anyhow::Result<Selection> {
    let findings_dir = corpus::layout::findings_dir(work_dir);
    let mut selection = Selection {
        eligible: Vec::new(),
        refused: Vec::new(),
        considered: 0,
    };
    // A work dir whose runs recorded nothing has no findings dir yet; a work
    // dir that does not exist is a mistyped path.
    let entries = match std::fs::read_dir(&findings_dir) {
        Ok(entries) => Some(entries),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound && work_dir.is_dir() => None,
        Err(error) => anyhow::bail!("cannot read {}: {error}", findings_dir.display()),
    };
    let mut records = Vec::new();
    for entry in entries.into_iter().flatten().flatten() {
        let dir = entry.path();
        let Some(raw) = read_json(&dir.join("finding.json")) else {
            continue;
        };
        let id = raw
            .get("id")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_owned();
        records.push(FindingRecord { id, dir, raw });
    }
    if let Some(want) = only {
        records.retain(|record| record.id == want);
        if records.is_empty() {
            let dir = findings_dir.join(want);
            let refusal = if corpus::layout::is_valid_finding_id(want) && dir.is_dir() {
                Refusal::Unreadable {
                    path: dir.join("finding.json"),
                }
            } else {
                Refusal::NotFound {
                    id: want.to_owned(),
                    findings_dir,
                }
            };
            selection.considered = 1;
            selection.refused.push(Refused {
                id: want.to_owned(),
                refusal,
                alternative: None,
            });
            return Ok(selection);
        }
    } else {
        records.retain(|record| {
            matches!(
                record.raw.get("classification").and_then(Value::as_str),
                Some("unhandled" | "oracle")
            )
        });
    }
    records.sort_by(|a, b| a.id.cmp(&b.id));
    selection.considered = records.len();
    for record in records {
        match assess(work_dir, &record, tool) {
            Ok(eligible) => selection.eligible.push((record, eligible)),
            Err(refusal) => {
                let alternative = alternative(work_dir, &record, &refusal);
                selection.refused.push(Refused {
                    id: record.id.clone(),
                    refusal,
                    alternative,
                });
            }
        }
    }
    Ok(selection)
}

/// Print each refusal to stderr with its alternative: `cannot <verb> <id>:
/// <reason>` for the one finding the operator asked for, else `<id> skipped:
/// <reason>` for at most `limit` findings (then a count of the rest).
pub(crate) fn print_refusals(tool: Tool, refused: &[Refused], requested: bool, limit: usize) {
    for item in refused.iter().take(limit) {
        if requested {
            bhfeprintln!(
                "{}: cannot {} {}: {}",
                tool.command(),
                tool.verb(),
                item.id,
                item.refusal.reason(tool)
            );
        } else {
            bhfeprintln!(
                "{}: {} skipped: {}",
                tool.command(),
                item.id,
                item.refusal.reason(tool)
            );
        }
        if let Some(alternative) = &item.alternative {
            bhfeprintln!("  reproduce it with: {alternative}");
        }
    }
    if refused.len() > limit {
        bhfeprintln!(
            "{}: ... and {} more finding(s) skipped",
            tool.command(),
            refused.len() - limit
        );
    }
}

/// What one run of capsule or env-capsule did with the findings it took.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct RunTally {
    /// A `--finding-id` was given.
    pub(crate) requested: bool,
    /// Capsules written.
    pub(crate) made: usize,
    /// Capsules verified to reproduce (replay).
    pub(crate) verified: usize,
    /// Findings whose capsule could not be written for an error.
    pub(crate) failed: usize,
}

/// The exit code capsule and env-capsule share: non-zero when a finding
/// failed, when nothing was written, and when a requested finding's capsule
/// did not verify. A run without `--finding-id` that wrote capsules exits 0
/// even when some did not verify (they say so) or some findings were skipped.
pub(crate) fn exit_code(tally: &RunTally) -> i32 {
    let requested_unverified = tally.requested && tally.verified < tally.made;
    if tally.failed > 0 || tally.made == 0 || requested_unverified {
        1
    } else {
        0
    }
}

/// Whether `tool` works on `finding`, and with what.
pub(crate) fn assess(
    work_dir: &Path,
    finding: &FindingRecord,
    tool: Tool,
) -> Result<Eligible, Refusal> {
    let classification = finding
        .raw
        .get("classification")
        .and_then(Value::as_str)
        .unwrap_or("");
    if classification != "unhandled" {
        return Err(Refusal::NotACrash {
            classification: classification.to_owned(),
        });
    }
    let harness_id = finding
        .raw
        .get("harness_id")
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|id| !id.is_empty())
        .ok_or(Refusal::NoHarness)?
        .to_owned();
    if !corpus::layout::is_valid_finding_id(&harness_id) {
        return Err(Refusal::InvalidHarnessId { harness_id });
    }
    let inputs = crash_inputs(&finding.dir);
    // An environment-driven crash can live entirely in the faked world, so
    // env-capsule also drives the harness from its corpus.
    if inputs.is_empty() && tool != Tool::EnvCapsule {
        return Err(Refusal::NoInput);
    }
    let dirs = harness_dirs(work_dir, &harness_id);
    let Some(language) = harness_language(&dirs, &harness_id) else {
        return Err(match dirs.first() {
            Some(dir) => Refusal::UnknownLanguage {
                harness_id,
                harness_dir: dir.clone(),
            },
            None => Refusal::HarnessNotFound {
                searched: harness_dir_candidates(work_dir, &harness_id),
                harness_id,
            },
        });
    };
    let Some(lane) = lane_for(&language) else {
        return Err(Refusal::UnsupportedLane {
            harness_id,
            language,
        });
    };
    if let Some(reason) = lane.tool_gap(tool) {
        return Err(Refusal::ToolNotForLane {
            harness_id,
            language: lane.tag().to_owned(),
            reason: format!("{} {reason}", tool.command()),
        });
    }
    match tool {
        Tool::Capsule => {
            let Some(first) = dirs.first() else {
                return Err(Refusal::HarnessNotFound {
                    searched: harness_dir_candidates(work_dir, &harness_id),
                    harness_id,
                });
            };
            let context = |dir: &Path| HarnessContext::new(work_dir, &harness_id, dir);
            match dirs
                .iter()
                .find(|dir| lane.harness_problem(&context(dir)).is_none())
            {
                Some(dir) => Ok(Eligible {
                    lane,
                    harness_id,
                    harness_dir: Some(dir.clone()),
                    binary: None,
                    inputs,
                }),
                None => Err(Refusal::IncompleteHarness {
                    problem: lane.harness_problem(&context(first)).unwrap_or_default(),
                    language: lane.tag().to_owned(),
                    harness_dir: first.clone(),
                    harness_id,
                }),
            }
        }
        Tool::Cartography | Tool::EnvCapsule => {
            let Some(binary) = lane.harness_binary(work_dir, &harness_id) else {
                return Err(Refusal::NotBuilt {
                    harness_id,
                    language: lane.tag().to_owned(),
                });
            };
            if tool == Tool::EnvCapsule && !is_dynamically_linked(&binary) {
                return Err(Refusal::ToolNotForLane {
                    harness_id,
                    language: lane.tag().to_owned(),
                    reason: format!(
                        "its executable {} is statically linked, so the runtrace shim {} \
                         records and replays the environment through cannot be preloaded \
                         into it",
                        binary.display(),
                        tool.command()
                    ),
                });
            }
            Ok(Eligible {
                lane,
                harness_dir: dirs.first().cloned(),
                harness_id,
                binary: Some(binary),
                inputs,
            })
        }
    }
}

/// Whether `path` is an ELF executable with a program interpreter (a
/// dynamically linked process the runtrace shim can be preloaded into). A file
/// that is not ELF (a launcher script, a Mach-O binary) counts as dynamic: the
/// check only refuses what it can prove static.
pub(crate) fn is_dynamically_linked(path: &Path) -> bool {
    const PT_INTERP: u32 = 3;
    let Ok(bytes) = read_prefix(path, 64 * 1024) else {
        return true;
    };
    if bytes.len() < 64 || &bytes[..4] != b"\x7fELF" {
        return true;
    }
    let class64 = bytes[4] == 2;
    let little = bytes[5] == 1;
    let u16_at = |at: usize| -> Option<u64> {
        let b = bytes.get(at..at + 2)?;
        Some(u64::from(if little {
            u16::from_le_bytes([b[0], b[1]])
        } else {
            u16::from_be_bytes([b[0], b[1]])
        }))
    };
    let u32_at = |at: usize| -> Option<u64> {
        let b: [u8; 4] = bytes.get(at..at + 4)?.try_into().ok()?;
        Some(u64::from(if little {
            u32::from_le_bytes(b)
        } else {
            u32::from_be_bytes(b)
        }))
    };
    let u64_at = |at: usize| -> Option<u64> {
        let b: [u8; 8] = bytes.get(at..at + 8)?.try_into().ok()?;
        Some(if little {
            u64::from_le_bytes(b)
        } else {
            u64::from_be_bytes(b)
        })
    };
    let (phoff, phentsize, phnum) = if class64 {
        (u64_at(0x20), u16_at(0x36), u16_at(0x38))
    } else {
        (u32_at(0x1c), u16_at(0x2a), u16_at(0x2c))
    };
    let (Some(phoff), Some(phentsize), Some(phnum)) = (phoff, phentsize, phnum) else {
        return true;
    };
    (0..phnum).any(|index| {
        usize::try_from(phoff + index * phentsize)
            .ok()
            .and_then(u32_at)
            .is_some_and(|kind| kind == PT_INTERP as u64)
    })
}

fn read_prefix(path: &Path, max: usize) -> std::io::Result<Vec<u8>> {
    use std::io::Read;
    let mut bytes = Vec::new();
    std::fs::File::open(path)?
        .take(max as u64)
        .read_to_end(&mut bytes)?;
    Ok(bytes)
}

/// A command that reproduces a refused finding without the refusing tool:
/// the finding's `replay.py`, else the built harness on the crash input with
/// sanitizer options. `None` when nothing could reproduce it.
pub(crate) fn alternative(
    work_dir: &Path,
    finding: &FindingRecord,
    refusal: &Refusal,
) -> Option<String> {
    if matches!(
        refusal,
        Refusal::NotFound { .. } | Refusal::Unreadable { .. } | Refusal::NoInput
    ) {
        return None;
    }
    let replay = finding.dir.join("replay.py");
    if replay.is_file() {
        // Windows' Python installer provides `python`, not `python3`.
        let python = if cfg!(windows) { "python" } else { "python3" };
        return Some(format!("{python} {}", sh_word(&replay.to_string_lossy())));
    }
    let harness_id = finding.raw.get("harness_id").and_then(Value::as_str)?;
    if !corpus::layout::is_valid_finding_id(harness_id) {
        return None;
    }
    let binary = native_harness_binary(work_dir, harness_id)?;
    let input = crash_inputs(&finding.dir).pop()?;
    // An Ada harness reads its input from stdin and reports through its event
    // log; the shared detector says which protocol the binary speaks.
    let detection = crate::protocol_detect::detect(&binary, &[work_dir]);
    if detection.protocol == crate::protocol_detect::HarnessProtocol::StdinEventLog
        && detection.basis != crate::protocol_detect::ProtocolBasis::Default
    {
        return Some(format!(
            "cat {} | BHF_EVENTS_PATH=\"$(mktemp)\" {}",
            sh_word(&input.to_string_lossy()),
            sh_word(&binary.to_string_lossy())
        ));
    }
    Some(direct_harness_command(
        &binary,
        &input,
        crate::replay::is_leak_finding(&finding.raw),
    ))
}

/// The built harness run on one input with the sanitizer options `bhf replay`
/// gives it ([`crate::fuzz::sanitizer_child_env`]): the first report halts the
/// run, UBSan prints its stack and check name, and a leak finding (`leak`)
/// keeps leak detection on. Your own `ASAN_OPTIONS`/`UBSAN_OPTIONS` are merged
/// first, as replay merges them, so the command reproduces like a replay.
pub(crate) fn direct_harness_command(binary: &Path, input: &Path, leak: bool) -> String {
    let mut words: Vec<String> = crate::fuzz::sanitizer_child_env(leak)
        .into_iter()
        .map(|(key, value)| format!("{key}={}", sh_word(&value)))
        .collect();
    words.push(sh_word(&binary.to_string_lossy()));
    words.push(sh_word(&input.to_string_lossy()));
    words.join(" ")
}

// ── harness lookup and language ─────────────────────────────────────────────

pub(crate) const GENERATION_METADATA: &str = "generation-metadata.json";

/// Every dir bhf may keep a harness in, in lookup order: the `bhf auto`
/// layouts, `generate-harness`'s default output, and `bhf build`'s.
pub(crate) fn harness_dir_candidates(work_dir: &Path, harness_id: &str) -> Vec<PathBuf> {
    let mut dirs = crate::auto::layout::harness_dir_candidates(work_dir, harness_id);
    dirs.push(work_dir.join("build").join(harness_id));
    dirs
}

/// The candidate harness dirs that exist.
pub(crate) fn harness_dirs(work_dir: &Path, harness_id: &str) -> Vec<PathBuf> {
    harness_dir_candidates(work_dir, harness_id)
        .into_iter()
        .filter(|dir| dir.is_dir())
        .collect()
}

/// The built executable of a native harness: `build/<id>/main` (`bhf build`),
/// then `main` in the harness dirs (`bhf auto` builds in place).
pub(crate) fn native_harness_binary(work_dir: &Path, harness_id: &str) -> Option<PathBuf> {
    let build = work_dir.join("build").join(harness_id);
    [build.join("main"), build.join("obj").join("main")]
        .into_iter()
        .chain(
            crate::auto::layout::harness_dir_candidates(work_dir, harness_id)
                .into_iter()
                .map(|dir| dir.join("main")),
        )
        .find(|path| path.is_file())
}

/// The language tag of a harness: generation metadata in the first dir that
/// has it, else the harness-id prefix, else the driver file a dir holds.
pub(crate) fn harness_language(dirs: &[PathBuf], harness_id: &str) -> Option<String> {
    if let Some(language) = dirs.iter().find_map(|dir| metadata_language(dir)) {
        return Some(language);
    }
    if let Some(language) = language_from_harness_id(harness_id) {
        return Some(language.to_owned());
    }
    dirs.iter()
        .find_map(|dir| driver_language(dir))
        .map(str::to_owned)
}

fn metadata_language(dir: &Path) -> Option<String> {
    read_json(&dir.join(GENERATION_METADATA))?
        .get("language")
        .and_then(Value::as_str)
        .map(|language| language.trim().to_ascii_lowercase())
        .filter(|language| !language.is_empty())
}

fn driver_language(dir: &Path) -> Option<&'static str> {
    // The lanes whose harness is a `main.c` with a language-specific glue
    // beside it are asked before the C lane, which recognises any `main.c`.
    RECOGNITION_ORDER
        .iter()
        .find(|lane| lane.recognizes(dir))
        .map(|lane| lane.tag())
}

/// The language `bhf auto` encodes in a harness id (`H-C0004-…` is C,
/// `H-X…` C++). A prefix only counts when the hex line number follows it, so a
/// custom id that happens to start with `H-C` is not taken for C.
pub(crate) fn language_from_harness_id(harness_id: &str) -> Option<&'static str> {
    const PREFIXES: &[(&str, &str)] = &[
        ("H-A", "ada"),
        ("H-C", "c"),
        ("H-X", "cpp"),
        ("H-R", "rust"),
        ("H-J", "java"),
        ("H-P", "python"),
        ("H-L", "perl"),
        ("H-G", "go"),
        ("H-B", "cobol"),
        ("H-F", "fortran"),
        ("H-S", "csharp"),
        ("H-N", "javascript"),
        ("H-T", "typescript"),
        ("H-U", "ruby"),
        ("H-V", "lua"),
        ("H-W", "php"),
    ];
    PREFIXES.iter().find_map(|(prefix, language)| {
        let rest = harness_id.strip_prefix(prefix)?;
        rest.chars()
            .next()
            .is_some_and(|c| c.is_ascii_digit() || ('A'..='F').contains(&c))
            .then_some(*language)
    })
}

/// A language tag as people write it.
pub(crate) fn language_name(tag: &str) -> String {
    match tag {
        "c" => "C",
        "cpp" | "c++" | "cxx" => "C++",
        "ada" => "Ada",
        "rust" => "Rust",
        "java" => "Java",
        "python" => "Python",
        "perl" => "Perl",
        "go" => "Go",
        "cobol" => "COBOL",
        "fortran" => "Fortran",
        "csharp" => "C#",
        "javascript" | "js" => "JavaScript",
        "typescript" | "ts" => "TypeScript",
        "ruby" => "Ruby",
        "lua" => "Lua",
        "php" => "PHP",
        other => return other.to_owned(),
    }
    .to_owned()
}

/// `C, C++, Ada, ...`: the languages with a lane.
pub(crate) fn supported_language_names() -> String {
    join_names(LANES.iter().map(|lane| lane.name()).collect())
}

/// The languages whose findings `tool` works on.
pub(crate) fn supported_language_names_for(tool: Tool) -> String {
    join_names(
        LANES
            .iter()
            .filter(|lane| lane.tool_gap(tool).is_none())
            .map(|lane| lane.name())
            .collect(),
    )
}

fn join_names(names: Vec<&str>) -> String {
    match names.split_last() {
        None => String::new(),
        Some((last, [])) => (*last).to_owned(),
        Some((last, rest)) => format!("{} and {last}", rest.join(", ")),
    }
}

