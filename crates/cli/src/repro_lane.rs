impl CFamilyLane {
    pub(crate) fn parse_makefile(&self, text: &str) -> MakefileFacts {
        let mut facts = MakefileFacts::default();
        let mut in_main = false;
        let standard_default = format!("{} ?=", self.standard_var);
        for line in text.lines() {
            if let Some(rest) = line.strip_prefix("COMPILE_DB_FLAGS =") {
                facts.compile_db_flags = crate::generate_harness::split_compile_command(rest);
            } else if let Some(rest) = line.strip_prefix("INCLUDES =") {
                facts.includes = crate::generate_harness::split_compile_command(rest);
            } else if let Some(rest) = line.strip_prefix("BUILD_CONTEXT_LDFLAGS =") {
                facts.link_flags = crate::generate_harness::split_compile_command(rest);
            } else if let Some(rest) = line.strip_prefix(&standard_default) {
                facts.default_standard = Some(rest.trim().to_owned()).filter(|s| !s.is_empty());
            } else if let Some(rest) = line.strip_prefix("BHF_DRIVER_SOURCE ?=") {
                facts.driver_source = crate::generate_harness::split_compile_command(rest)
                    .into_iter()
                    .next();
            }
            if line.starts_with("main:") {
                in_main = true;
                continue;
            }
            if !in_main {
                continue;
            }
            if !line.starts_with('\t') {
                in_main = line.trim().is_empty();
                continue;
            }
            in_main = false;
            // `$(CXX) ... -o $@ main.cpp <sources> $(CONTEXT_MAIN_OBJECTS) ...`:
            // the explicit target sources sit between the driver and the first
            // make variable. Match the driver as a whole word: `main.c` is a
            // prefix of `main.cpp`.
            let tokens = crate::generate_harness::split_compile_command(line.trim());
            let Some(at) = tokens
                .windows(3)
                .position(|w| w[0] == "-o" && w[1] == "$@" && w[2] == self.driver)
            else {
                continue;
            };
            facts.has_main_rule = true;
            facts.target_sources = tokens[at + 3..]
                .iter()
                .take_while(|token| !token.starts_with("$("))
                .map(PathBuf::from)
                .collect();
        }
        facts
    }

    fn build_model(&self, harness_dir: &Path) -> anyhow::Result<BuildModel> {
        let harness_dir = normalize(&std::path::absolute(harness_dir)?);
        let makefile = harness_dir.join("Makefile");
        let text = std::fs::read_to_string(&makefile)
            .map_err(|error| anyhow::anyhow!("cannot read {}: {error}", makefile.display()))?;
        let facts = self.parse_makefile(&text);
        if !facts.has_main_rule {
            anyhow::bail!(
                "{} has no `main` rule that compiles {}",
                makefile.display(),
                self.driver
            );
        }
        let recipe = read_recorded_recipe(&harness_dir);
        let repairs = harness_dir.join("repairs");
        let mut warnings = Vec::new();
        let units = per_translation_units(&harness_dir, &mut warnings);
        let unit_sources: BTreeSet<PathBuf> = units.iter().map(|u| u.source.clone()).collect();
        let target_sources: Vec<PathBuf> = facts
            .target_sources
            .iter()
            .map(|source| absolute(&source.to_string_lossy(), &harness_dir))
            .collect();
        // With a recorded recipe, its extra sources are exactly what the build
        // linked (repair stubs included); without one, ship the repair stubs.
        let candidates = match &recipe {
            Some(recipe) => recipe.extra_sources.clone(),
            None => self.repair_stub_sources(&repairs),
        };
        let mut seen: BTreeSet<PathBuf> = target_sources.iter().cloned().collect();
        seen.extend(unit_sources);
        let mut extra_sources = Vec::new();
        for source in candidates {
            let source = absolute(&source.to_string_lossy(), &harness_dir);
            if is_provenance_stub(&source) || !seen.insert(source.clone()) {
                continue;
            }
            extra_sources.push(source);
        }
        let mut extra_includes = Vec::new();
        for name in [
            crate::auto::repair::AUTO_CPP_INCLUDES_FILE,
            crate::auto::repair::AUTO_DEFINES_FILE,
        ] {
            let header = repairs.join(name);
            if header.is_file() {
                extra_includes.push(Arg::Split("-include", header));
            }
        }
        if let Some(recipe) = &recipe {
            for dir in &recipe.extra_includes {
                let dir = absolute(&dir.to_string_lossy(), &harness_dir);
                extra_includes.push(Arg::Split("-iquote", dir.clone()));
                extra_includes.push(Arg::Split("-idirafter", dir));
            }
        }
        let compat_flags = if self.standard_leads {
            Vec::new()
        } else {
            read_compat_flags(&harness_dir)
        };
        let mut link_flags = Vec::new();
        for arg in parse_args(&facts.link_flags, &harness_dir) {
            // A prebuilt object or archive named by path ships with the capsule.
            match arg {
                Arg::Text(text) if !text.starts_with('-') => {
                    let path = absolute(&text, &harness_dir);
                    link_flags.push(if path.is_file() {
                        Arg::File(path)
                    } else {
                        Arg::Text(text)
                    });
                }
                other => link_flags.push(other),
            }
        }
        Ok(BuildModel {
            driver: harness_dir.join(self.driver),
            compile_db_flags: parse_args(&facts.compile_db_flags, &harness_dir),
            includes: parse_args(&facts.includes, &harness_dir),
            standard: recipe
                .as_ref()
                .and_then(|recipe| recipe.standard.clone())
                .filter(|standard| !standard.trim().is_empty())
                .or(facts.default_standard),
            recorded_recipe: recipe.is_some(),
            compiler: self.capsule_compiler(&harness_dir),
            windows_compiler: self.windows_compiler(&harness_dir, recipe.as_ref()),
            driver_source: facts
                .driver_source
                .as_deref()
                .map(|source| absolute(source, &harness_dir)),
            harness_dir,
            target_sources,
            extra_sources,
            units,
            extra_includes,
            compat_flags,
            link_flags,
            rebuilt_objects: Vec::new(),
            prelude: String::new(),
            extra_link: Vec::new(),
            extra_files: Vec::new(),
            generated_sources: Vec::new(),
            facts: serde_json::Map::new(),
            warnings,
        })
    }

    /// The compiler the capsule rebuilds with: `$CC`/`$CXX` when set, else the
    /// family that built the harness binary (a gcc-built harness rebuilds with
    /// gcc), else the lane's default.
    fn capsule_compiler(&self, harness_dir: &Path) -> CapsuleCompiler {
        let toolchain = self.tools[0];
        let cxx = self.probe_language == "c++";
        if let Some(command) = env_value(toolchain.env_var) {
            let family = crate::toolchain::compiler_family(&command, cxx)
                .or_else(|| {
                    command_words(&command)
                        .iter()
                        .rev()
                        .find_map(|word| harness_gen::compiler_family::family_from_name(word))
                })
                .unwrap_or(CompilerFamily::Clang);
            return CapsuleCompiler {
                command,
                family,
                source: "environment",
            };
        }
        let built = [harness_dir.join("main"), harness_dir.join("obj/main")]
            .iter()
            .find_map(|binary| binary_compiler_family(binary));
        match built {
            Some(CompilerFamily::Gcc) => CapsuleCompiler {
                command: if cxx { "g++" } else { "gcc" }.to_owned(),
                family: CompilerFamily::Gcc,
                source: "harness binary",
            },
            Some(CompilerFamily::Clang) => CapsuleCompiler {
                command: toolchain.default.to_owned(),
                family: CompilerFamily::Clang,
                source: "harness binary",
            },
            // The probe reads ELF notes only, so it never names cl; a harness
            // it cannot attribute rebuilds with the lane's default.
            Some(CompilerFamily::Msvc) | None => CapsuleCompiler {
                command: toolchain.default.to_owned(),
                family: CompilerFamily::Clang,
                source: "default",
            },
        }
    }

    /// The compiler build.ps1 rebuilds with by default: `$CC`/`$CXX` when it
    /// names a Windows compiler (bhf's cl front end: the compiler it runs),
    /// else the family recorded for the harness (its `bhf_toolchain.stamp`;
    /// for the MSVC lane, the compiler the front end ran, from the build
    /// recipe), else clang. gcc has no Windows AddressSanitizer, so a
    /// gcc-built harness rebuilds with clang there.
    fn windows_compiler(
        &self,
        harness_dir: &Path,
        recipe: Option<&RecordedRecipe>,
    ) -> windows::WindowsCompiler {
        use windows::{Dialect, WindowsCompiler};
        let cxx = self.probe_language == "c++";
        let named = |dialect: Dialect, source| WindowsCompiler {
            dialect,
            program: dialect.program(cxx).to_owned(),
            source,
        };
        if let Some(command) = env_value(self.tools[0].env_var) {
            if let Some(real) = crate::msvc_cc::front_end_compiler(&command) {
                let dialect = Dialect::of_compiler(&real)
                    .filter(|dialect| *dialect != Dialect::Clang)
                    .unwrap_or(Dialect::Cl);
                return named(dialect, "environment");
            }
            if let Some(dialect) = Dialect::of_compiler(&command) {
                return WindowsCompiler {
                    dialect,
                    program: command,
                    source: "environment",
                };
            }
        }
        match recorded_compiler_family(harness_dir) {
            Some(CompilerFamily::Msvc) => {
                let dialect = recipe
                    .and_then(|recipe| recipe.msvc_compiler.as_deref())
                    .and_then(Dialect::of_compiler)
                    .filter(|dialect| *dialect != Dialect::Clang)
                    .unwrap_or(Dialect::Cl);
                named(dialect, "recorded build")
            }
            Some(CompilerFamily::Clang) => named(Dialect::Clang, "recorded build"),
            Some(CompilerFamily::Gcc) | None => named(Dialect::Clang, "default"),
        }
    }

    fn repair_stub_sources(&self, repairs: &Path) -> Vec<PathBuf> {
        let mut sources: Vec<PathBuf> = std::fs::read_dir(repairs)
            .into_iter()
            .flatten()
            .flatten()
            .map(|entry| entry.path())
            .filter(|path| {
                path.is_file()
                    && path
                        .extension()
                        .and_then(|ext| ext.to_str())
                        .is_some_and(|ext| self.stub_extensions.contains(&ext))
            })
            .collect();
        sources.sort();
        sources
    }

    /// The flags every compile of this lane starts with, through the language
    /// standard when it leads. `sanitize` stands for the sanitizer flags (the
    /// family's own for a scan, [`SANITIZE_WORD`] for build.sh).
    fn leading_flags(&self, standard: Option<&str>, sanitize: &[String]) -> Vec<String> {
        let mut flags: Vec<String> = OPT_FLAGS.iter().map(|f| (*f).to_owned()).collect();
        flags.extend(sanitize.iter().cloned());
        if self.standard_leads {
            if let Some(standard) = standard {
                flags.push(format!("-std={standard}"));
            }
        }
        flags.extend(SECTION_FLAGS.iter().map(|f| (*f).to_owned()));
        flags
    }

    /// The sanitizer (and clang-only lane) flags `family` takes.
    fn sanitize_flags(&self, family: CompilerFamily) -> Vec<String> {
        let mut flags = family_sanitizer_flags(family);
        if family == CompilerFamily::Clang {
            flags.extend(self.clang_lane_flags.iter().map(|f| (*f).to_owned()));
        }
        flags
    }

    /// The full argument list (no output, no inputs) of the `main` compile.
    fn main_args(
        &self,
        model: &BuildModel,
        sanitize: &[String],
        map: &dyn Fn(&Path) -> String,
    ) -> Vec<String> {
        let mut args = self.leading_flags(model.standard.as_deref(), sanitize);
        args.extend(model.compat_flags.iter().cloned());
        args.extend(FEATURE_TEST_FLAGS.iter().map(|f| (*f).to_owned()));
        args.extend(model.compile_db_flags.iter().flat_map(|a| a.render(map)));
        if !self.standard_leads {
            if let Some(standard) = &model.standard {
                args.push(format!("-std={standard}"));
            }
        }
        args.extend(model.includes.iter().flat_map(|a| a.render(map)));
        args.extend(model.extra_includes.iter().flat_map(|a| a.render(map)));
        args
    }

    /// The argument list (no output, no input) of one per-TU compile.
    fn unit_args(
        &self,
        model: &BuildModel,
        unit: &Unit,
        sanitize: &[String],
        map: &dyn Fn(&Path) -> String,
    ) -> Vec<String> {
        let mut args = self.leading_flags(model.standard.as_deref(), sanitize);
        args.extend(model.compat_flags.iter().cloned());
        args.extend(unit.flags.iter().flat_map(|a| a.render(map)));
        args.extend(model.includes.iter().flat_map(|a| a.render(map)));
        args.extend(model.extra_includes.iter().flat_map(|a| a.render(map)));
        args
    }

    fn plan_from_model(&self, model: &BuildModel) -> anyhow::Result<CapsulePlan> {
        let mut warnings = model.warnings.clone();
        let rebuilt: BTreeSet<&PathBuf> = model.rebuilt_objects.iter().map(|o| &o.object).collect();
        let explicit = std::iter::once(&model.driver)
            .chain(model.target_sources.iter().filter(|p| !rebuilt.contains(p)))
            .chain(&model.extra_sources)
            .chain(model.units.iter().map(|unit| &unit.source))
            .chain(model.rebuilt_objects.iter().map(|object| &object.source));
        for path in explicit {
            if !path.is_file() {
                anyhow::bail!(
                    "{} is part of the harness build but no longer exists",
                    path.display()
                );
            }
        }
        let compiler = &model.compiler.command;
        let family = model.compiler.family;
        let scan_sanitize = self.sanitize_flags(family);
        // A clang++ that picked a GCC install without its libstdc++ headers
        // cannot compile `<string>`; bhf's C++ builds then add the newest
        // installed libstdc++ headers (crate::build), and so does the scan
        // (or, on a libc++ host, the libc++ headers).
        let stdlib_flags = if self.recovers_cpp_stdlib {
            cpp_stdlib_flags(compiler)
        } else {
            Vec::new()
        };
        let system = system_include_dirs(compiler, self.probe_language);
        let is_system = |path: &Path| system.iter().any(|dir| path.starts_with(dir));
        let original = |path: &Path| path.to_string_lossy().into_owned();

        // 1. The files the build reads: its inputs plus the include closure the
        //    compiler reports (`-M` lists every header a TU includes, however
        //    deep and through whichever include root).
        let mut files: BTreeSet<PathBuf> = BTreeSet::new();
        files.insert(model.driver.clone());
        files.extend(
            model
                .target_sources
                .iter()
                .filter(|p| !rebuilt.contains(p))
                .cloned(),
        );
        files.extend(model.extra_sources.iter().cloned());
        files.extend(model.units.iter().map(|u| u.source.clone()));
        files.extend(model.rebuilt_objects.iter().map(|o| o.source.clone()));
        files.extend(model.extra_files.iter().cloned());
        for arg in model.extra_includes.iter().chain(&model.compile_db_flags) {
            if let Arg::Split("-include" | "-imacros", path) = arg {
                files.insert(path.clone());
            }
        }
        files.extend(model.link_flags.iter().filter_map(|a| match a {
            Arg::File(path) => Some(path.clone()),
            _ => None,
        }));
        let main_inputs: Vec<PathBuf> = std::iter::once(model.driver.clone())
            .chain(model.target_sources.iter().cloned())
            .chain(model.extra_sources.iter().cloned())
            .filter(|path| has_extension(path, SOURCE_EXTENSIONS))
            .collect();
        let mut scans = vec![(
            self.main_args(model, &scan_sanitize, &original),
            main_inputs,
        )];
        for unit in &model.units {
            scans.push((
                self.unit_args(model, unit, &scan_sanitize, &original),
                vec![unit.source.clone()],
            ));
        }
        let mut closure = "compiler";
        for (args, inputs) in &mut scans {
            args.extend(stdlib_flags.iter().cloned());
            match dependency_closure(compiler, &model.harness_dir, args, inputs) {
                Some(deps) => files.extend(deps.into_iter().filter(|dep| !is_system(dep))),
                None => closure = "header-scan",
            }
        }

        // 2. Where each file goes. The harness dir, its repairs and the C
        //    runtime have fixed homes; every other file keeps its path relative
        //    to the deepest dir holding all of them (and every project include
        //    root), so `#include "sub/x.h"` and `"../x.h"` still resolve.
        let repairs = model.harness_dir.join("repairs");
        let runtime_dirs: Vec<PathBuf> = model
            .includes
            .iter()
            .filter_map(Arg::include_dir)
            .filter(|dir| dir.join("bhf_decode.h").is_file())
            .map(Path::to_path_buf)
            .collect();
        let mut mounts: Vec<(PathBuf, String)> = vec![
            (repairs.clone(), "stubs".to_owned()),
            (model.harness_dir.clone(), "harness".to_owned()),
        ];
        for (index, dir) in runtime_dirs.iter().enumerate() {
            let name = if index == 0 {
                "runtime".to_owned()
            } else {
                format!("runtime_{index}")
            };
            mounts.push((dir.clone(), name));
        }
        let fixed = |path: &Path| mounts.iter().any(|(dir, _)| path.starts_with(dir));
        let project_roots: Vec<PathBuf> = model
            .includes
            .iter()
            .chain(&model.extra_includes)
            .chain(&model.compile_db_flags)
            .chain(model.units.iter().flat_map(|u| &u.flags))
            .filter_map(Arg::include_dir)
            .filter(|dir| dir.is_dir() && !is_system(dir) && !fixed(dir))
            .map(Path::to_path_buf)
            .collect();
        if closure == "header-scan" {
            let mut budget = ScanBudget::default();
            let mut roots: Vec<PathBuf> = project_roots.clone();
            roots.extend(
                files
                    .iter()
                    .filter(|path| !fixed(path))
                    .filter_map(|path| path.parent().map(Path::to_path_buf)),
            );
            roots.push(repairs.clone());
            roots.extend(runtime_dirs.iter().cloned());
            roots.sort();
            roots.dedup();
            for root in &roots {
                scan_headers(root, &model.harness_dir, &mut budget, &mut files);
            }
            scan_shallow_headers(&model.harness_dir, &mut files);
            // A header outside every root (`#include "../common/defs.h"`) is
            // found by following the include lines themselves.
            let search: Vec<PathBuf> = model
                .includes
                .iter()
                .chain(&model.extra_includes)
                .chain(&model.compile_db_flags)
                .chain(model.units.iter().flat_map(|u| &u.flags))
                .filter_map(Arg::include_dir)
                .filter(|dir| dir.is_dir() && !is_system(dir))
                .map(Path::to_path_buf)
                .collect();
            follow_includes(&mut files, &search, &is_system, &mut budget);
            if budget.truncated {
                warnings.push(format!(
                    "the compiler could not list the build's includes, and the header copy \
                     stopped at {MAX_SCANNED_FILES} files / {} MiB",
                    MAX_SCANNED_BYTES / (1024 * 1024)
                ));
            } else {
                warnings.push(
                    "the compiler could not list the build's includes; every header under \
                     the include roots was copied instead"
                        .to_owned(),
                );
            }
        }
        let project_files: Vec<&PathBuf> = files
            .iter()
            .filter(|path| !fixed(path) && !is_system(path))
            .collect();
        let anchors = project_files
            .iter()
            .filter_map(|path| path.parent())
            .chain(project_roots.iter().map(PathBuf::as_path));
        if let Some(root) = common_ancestor(anchors) {
            mounts.push((root, "sources".to_owned()));
        }
        // Longest prefix wins: `repairs/` inside the harness dir, a harness dir
        // inside the project tree.
        mounts.sort_by_key(|(dir, _)| std::cmp::Reverse(dir.components().count()));
        let place = |path: &Path| -> Option<String> {
            mounts.iter().find_map(|(dir, name)| {
                let rel = path.strip_prefix(dir).ok()?;
                let rel = rel.to_string_lossy().replace('\\', "/");
                Some(if rel.is_empty() {
                    name.clone()
                } else {
                    format!("{name}/{rel}")
                })
            })
        };
        // An object build.sh compiles from source lives in `obj/`.
        let rebuilt_place: Vec<(PathBuf, String)> = model
            .rebuilt_objects
            .iter()
            .enumerate()
            .map(|(index, object)| {
                let stem = object
                    .object
                    .file_stem()
                    .map(|stem| stem.to_string_lossy().into_owned())
                    .unwrap_or_else(|| "object".to_owned());
                (object.object.clone(), format!("obj/{index}_{stem}.o"))
            })
            .collect();
        let capsule_path = |path: &Path| -> String {
            if let Some((_, to)) = rebuilt_place.iter().find(|(object, _)| object == path) {
                return to.clone();
            }
            if is_system(path) {
                return original(path);
            }
            place(path).unwrap_or_else(|| original(path))
        };

        let mut copies = Vec::new();
        for path in &files {
            if is_system(path) || !path.is_file() || rebuilt.contains(path) {
                continue;
            }
            match place(path) {
                Some(to) => copies.push(CapsuleFile {
                    from: path.clone(),
                    to,
                }),
                None => warnings.push(format!("{} has no place in the capsule", path.display())),
            }
        }
        // bhf's driver ships with the runtime headers: build.ps1 links it
        // beside the harness, as the Makefile does.
        let driver_place = match (&model.driver_source, self.glue) {
            (Some(source), None) if source.is_file() => place(source),
            _ => None,
        };
        if let (Some(source), Some(to)) = (&model.driver_source, &driver_place) {
            if !copies.iter().any(|copy| copy.to == *to) {
                copies.push(CapsuleFile {
                    from: source.clone(),
                    to: to.clone(),
                });
            }
        }

        // 3. build.sh: per-TU objects first, then the `main` link, all relative.
        let compiler_var = self.tools[0].env_var;
        let mut script = format!(
            "#!/bin/sh\n\
             # Rebuild this bhf PoC offline. Needs only {} and a shell.\n\
             set -e\n\
             cd \"$(dirname \"$0\")\"\n\
             {compiler_var}=\"${{{compiler_var}:-{}}}\"\n\
             {}\
             {}\
             case \"$(uname -s)\" in\n\
             \x20 Darwin) GC_LDFLAGS=-Wl,-dead_strip ;;\n\
             \x20 *) GC_LDFLAGS=-Wl,--gc-sections ;;\n\
             esac\n",
            describe_requirements(&self.requirements(model)),
            sh_double_quoted(compiler),
            compiler_runner(compiler_var),
            self.sanitize_selection(family),
        );
        let (stdlib_cflags, stdlib_ldflags) = if self.recovers_cpp_stdlib {
            script.push_str(&cpp_stdlib_fallback(compiler_var));
            (" $STDLIB_FLAGS", " $STDLIB_LDFLAGS")
        } else {
            ("", "")
        };
        script.push_str(&model.prelude);
        let mut objects = Vec::new();
        if !model.units.is_empty() || !model.rebuilt_objects.is_empty() {
            script.push_str("mkdir -p obj\n");
        }
        script.push_str(&rebuilt_object_steps(
            model
                .rebuilt_objects
                .iter()
                .zip(&rebuilt_place)
                .map(|(object, (_, to))| {
                    format!(
                        "\"${}\" {} -c {} -o {to}",
                        object.compiler_var,
                        shell_words(&object.flags),
                        sh_word(&capsule_path(&object.source)),
                    )
                })
                .collect(),
        ));
        let sanitize = [SANITIZE_WORD.to_owned()];
        for (index, unit) in model.units.iter().enumerate() {
            let object = format!("obj/unit_{index}.o");
            let args = shell_words(&self.unit_args(model, unit, &sanitize, &capsule_path));
            script.push_str(&format!(
                "cc_run {args}{stdlib_cflags} \\\n\x20 -c {} -o {object}\n",
                sh_word(&capsule_path(&unit.source))
            ));
            objects.push(object);
        }
        let mut inputs = vec![capsule_path(&model.driver)];
        inputs.extend(model.target_sources.iter().map(|p| capsule_path(p)));
        inputs.extend(objects);
        inputs.extend(model.extra_sources.iter().map(|p| capsule_path(p)));
        inputs.extend(model.generated_sources.iter().map(|(to, _)| to.clone()));
        // Objects the link took from outside the Makefile (a Fortran link
        // closure) follow the explicit inputs.
        for (object, (_, to)) in model.rebuilt_objects.iter().zip(&rebuilt_place) {
            if !model.target_sources.contains(&object.object) {
                inputs.push(to.clone());
            }
        }
        let link: Vec<String> = model
            .link_flags
            .iter()
            .flat_map(|a| a.render(&capsule_path))
            .collect();
        let link_words = shell_words(&link);
        let extra_link = model.extra_link.join(" ");
        script.push_str(&format!(
            "cc_run {}{stdlib_cflags} \\\n\x20 -o poc {} $GC_LDFLAGS{stdlib_ldflags}{}{}\n",
            shell_words(&self.main_args(model, &sanitize, &capsule_path)),
            shell_words(&inputs),
            if link_words.is_empty() {
                String::new()
            } else {
                format!(" {link_words}")
            },
            if extra_link.is_empty() {
                String::new()
            } else {
                format!(" {extra_link}")
            },
        ));

        // 4. build.ps1: the same build for Windows, without a POSIX shell.
        let mut generated: Vec<GeneratedFile> = model
            .generated_sources
            .iter()
            .map(|(to, text)| GeneratedFile {
                to: to.clone(),
                bytes: text.clone().into_bytes(),
                executable: false,
            })
            .collect();
        let windows = match &driver_place {
            Some(driver) => match self.windows_build(model, &capsule_path, &copies, driver) {
                Ok((build, stubs)) => {
                    generated.extend(stubs);
                    Some(build)
                }
                Err(error) => {
                    warnings.push(format!("no build.ps1 (Windows rebuild): {error}"));
                    None
                }
            },
            None => {
                if cfg!(windows) && self.glue.is_none() {
                    warnings.push(
                        "no build.ps1 (Windows rebuild): the harness Makefile names no bhf \
                         driver source (BHF_DRIVER_SOURCE) for it to link"
                            .to_owned(),
                    );
                }
                None
            }
        };

        let mut layout = vec![(
            format!("harness/{}", self.driver),
            "the fuzz driver (decodes the input, calls the target)".to_owned(),
        )];
        let has = |prefix: &str| copies.iter().any(|c| c.to.starts_with(prefix));
        if has("sources/") {
            layout.push((
                "sources/".to_owned(),
                "the target sources and the project headers they include, in their original \
                 layout"
                    .to_owned(),
            ));
        }
        if has("stubs/") {
            layout.push((
                "stubs/".to_owned(),
                "the stubs and placeholder headers bhf synthesized to make the tree build"
                    .to_owned(),
            ));
        }
        if has("runtime") {
            layout.push((
                "runtime/".to_owned(),
                if windows.is_some() {
                    "the bhf decode-runtime headers and bhf's driver (`bhf_driver.c`, which \
                     build.ps1 links)"
                } else {
                    "the bhf decode-runtime headers"
                }
                .to_owned(),
            ));
        }
        if windows.is_some() {
            layout.push((
                "build.ps1".to_owned(),
                "the Windows build: compiles .\\poc.exe with cl, clang-cl or clang, no POSIX \
                 shell needed"
                    .to_owned(),
            ));
        }
        let mut facts = serde_json::Map::new();
        facts.insert("compiler_env".to_owned(), json!(compiler_var));
        facts.insert("default_compiler".to_owned(), json!(self.tools[0].default));
        facts.insert("compiler".to_owned(), json!(compiler));
        facts.insert("compiler_family".to_owned(), json!(family.make_value()));
        facts.insert("compiler_source".to_owned(), json!(model.compiler.source));
        facts.insert("standard".to_owned(), json!(model.standard));
        facts.insert("recorded_recipe".to_owned(), json!(model.recorded_recipe));
        facts.insert("extra_sources".to_owned(), json!(model.extra_sources.len()));
        facts.insert("translation_units".to_owned(), json!(model.units.len()));
        facts.insert("include_closure".to_owned(), json!(closure));
        facts.insert(
            "stdlib_include_fallback".to_owned(),
            json!(!stdlib_flags.is_empty()),
        );
        if windows.is_some() {
            let recorded = &model.windows_compiler;
            facts.insert("windows_compiler".to_owned(), json!(recorded.program));
            facts.insert(
                "windows_compiler_dialect".to_owned(),
                json!(recorded.dialect.label()),
            );
            facts.insert("windows_compiler_source".to_owned(), json!(recorded.source));
        }
        facts.extend(model.facts.clone());
        Ok(CapsulePlan {
            build_facts: Value::Object(facts),
            files: copies,
            generated,
            build_script: script,
            build_summary: "compile ./poc (ASan+UBSan)".to_owned(),
            requires: self.requirements(model),
            layout,
            build_outputs: [&["poc", "obj"][..], WINDOWS_BUILD_OUTPUTS].concat(),
            warnings,
            windows,
        })
    }

    /// build.ps1 for this harness: the Makefile's build (bhf's driver linked
    /// beside the harness, its sanitizer and coverage flags) in each Windows
    /// dialect, the recorded one the default, plus the MSVC copies of weak
    /// repair stubs cl needs. `driver` is the capsule path of bhf's driver.
    fn windows_build(
        &self,
        model: &BuildModel,
        capsule_path: &dyn Fn(&Path) -> String,
        copies: &[CapsuleFile],
        driver: &str,
    ) -> Result<(WindowsBuild, Vec<GeneratedFile>), String> {
        use windows::{Dialect, DialectBuild, Step};
        let cxx = self.probe_language == "c++";
        let arch = env_value("VSCMD_ARG_TGT_ARCH")
            .map(|arch| arch.to_ascii_lowercase())
            .unwrap_or_else(|| "x64".to_owned());
        // The GCC-style command lines: bhf's driver, each per-TU object, then
        // the harness compiled and linked with them (the Makefile's `main`).
        let commands = |sanitize: &[String], ext: &str| -> Vec<(String, Vec<String>)> {
            let words = |words: &[&str]| words.iter().map(|w| (*w).to_owned()).collect::<Vec<_>>();
            let driver_object = format!("obj/bhf_driver.{ext}");
            let mut driver_args = if cxx { words(&["-x", "c"]) } else { Vec::new() };
            driver_args.extend(words(OPT_FLAGS));
            driver_args.extend(words(FEATURE_TEST_FLAGS));
            driver_args.extend(words(&["-c", driver, "-o", &driver_object]));
            let mut commands = vec![("bhf_driver".to_owned(), driver_args)];
            let mut objects = Vec::new();
            for (index, unit) in model.units.iter().enumerate() {
                let object = format!("obj/unit_{index}.{ext}");
                let mut args = self.unit_args(model, unit, sanitize, capsule_path);
                args.extend([
                    "-c".to_owned(),
                    capsule_path(&unit.source),
                    "-o".to_owned(),
                    object.clone(),
                ]);
                commands.push((format!("unit_{index}"), args));
                objects.push(object);
            }
            let mut args = self.main_args(model, sanitize, capsule_path);
            args.extend(words(&["-DBHF_EXTERNAL_DRIVER", "-o", "poc.exe"]));
            args.push(capsule_path(&model.driver));
            args.extend(model.target_sources.iter().map(|p| capsule_path(p)));
            args.extend(objects);
            args.extend(model.extra_sources.iter().map(|p| capsule_path(p)));
            args.push(driver_object);
            args.extend(model.link_flags.iter().flat_map(|a| a.render(capsule_path)));
            // The linker's own spelling of `--gc-sections`, which link.exe and
            // lld-link take from clang and from cl alike.
            args.push("-Wl,/OPT:REF".to_owned());
            commands.push(("link".to_owned(), args));
            commands
        };
        let mut clang_sanitize = self.sanitize_flags(CompilerFamily::Clang);
        clang_sanitize.push(CompilerFamily::Clang.coverage_flag().to_owned());
        let msvc_sanitize = vec![
            "-fsanitize=address".to_owned(),
            CompilerFamily::Msvc.coverage_flag().to_owned(),
        ];
        // cl has no weak symbols: bhf's weak repair stubs compile from MSVC
        // copies, as the bhf-cl front end compiles them.
        let msvc_commands = commands(&msvc_sanitize, "obj");
        let mut weak = std::collections::BTreeMap::new();
        let mut stubs = Vec::new();
        for (_, args) in &msvc_commands {
            for arg in args {
                let Some(rest) = arg.strip_prefix("stubs/") else {
                    continue;
                };
                if weak.contains_key(arg) || !has_extension(Path::new(arg), SOURCE_EXTENSIONS) {
                    continue;
                }
                let Some(copy) = copies.iter().find(|copy| copy.to == *arg) else {
                    continue;
                };
                let Ok(text) = std::fs::read_to_string(&copy.from) else {
                    continue;
                };
                if !text.contains("__attribute__((weak))") {
                    continue;
                }
                let cpp = !has_extension(Path::new(arg), &["c"]);
                let to = format!("stubs_msvc/{rest}");
                stubs.push(GeneratedFile {
                    to: to.clone(),
                    bytes: crate::msvc_cc::msvc_weak_symbols(&text, cpp, arch == "x86")
                        .into_bytes(),
                    executable: false,
                });
                let dir = Path::new(arg)
                    .parent()
                    .map(|dir| dir.to_string_lossy().into_owned())
                    .unwrap_or_else(|| "stubs".to_owned());
                weak.insert(arg.clone(), (to, dir));
            }
        }
        let mut builds = Vec::new();
        for dialect in Dialect::ALL {
            let build = match dialect.backend() {
                Some(backend) => windows::cl_build(&msvc_commands, backend, &weak)?,
                None => DialectBuild {
                    steps: commands(&clang_sanitize, "o")
                        .into_iter()
                        .map(|(name, args)| Step { name, args })
                        .collect(),
                    include_after: Vec::new(),
                },
            };
            builds.push((dialect, build));
        }
        let toolchain = self.tools[0];
        let recorded = &model.windows_compiler;
        let script = windows::render(&windows::ScriptInputs {
            compiler_var: toolchain.env_var,
            cxx,
            recorded,
            arch: &arch,
            builds: &builds,
        });
        let mut requirement = Requirement::new(
            toolchain.env_var,
            &recorded.program,
            toolchain.purpose,
            toolchain.version_args,
        );
        requirement.alternatives = windows::candidates(recorded, cxx)
            .into_iter()
            .skip(1)
            .collect();
        Ok((
            WindowsBuild {
                script,
                requires: vec![requirement],
            },
            stubs,
        ))
    }

    /// The programs the rebuild needs: the recorded compiler, then the lane's
    /// others (a COBOL runtime's, a Fortran compiler).
    fn requirements(&self, model: &BuildModel) -> Vec<Requirement> {
        let toolchain = self.tools[0];
        let mut requires = vec![Requirement::new(
            toolchain.env_var,
            &model.compiler.command,
            toolchain.purpose,
            toolchain.version_args,
        )];
        requires.extend(self.tools[1..].iter().map(Toolchain::requirement));
        requires
    }

    /// The build.sh lines that set `$SANITIZE` to the sanitizer flags of the
    /// compiler that runs the script, asking it which family it is
    /// (`-dM -E`), as the harness Makefile does; `recorded` when it cannot say.
    fn sanitize_selection(&self, recorded: CompilerFamily) -> String {
        let flags = |family: CompilerFamily| self.sanitize_flags(family).join(" ");
        format!(
            "# The sanitizer flags of the compiler that runs: gcc spells them differently\n\
             # from clang (it has no `function` UBSan check).\n\
             case \"$( (echo | cc_run -dM -E -x {lang} -) 2>/dev/null)\" in\n\
             \x20 *__clang__*) CC_FAMILY=clang ;;\n\
             \x20 *__GNUC__*) CC_FAMILY=gcc ;;\n\
             \x20 *) CC_FAMILY={recorded} ;;\n\
             esac\n\
             if [ \"$CC_FAMILY\" = gcc ]; then SANITIZE=\"{gcc}\"; else SANITIZE=\"{clang}\"; fi\n",
            lang = self.probe_language,
            recorded = recorded.make_value(),
            gcc = flags(CompilerFamily::Gcc),
            clang = flags(CompilerFamily::Clang),
        )
    }
}

