    /// The fallback follows `#include` lines from the known files: through
    /// `..` out of every root, transitively, through a search dir for an
    /// angled name, and never into system files.
    #[test]
    fn included_project_headers_are_followed_out_of_the_roots() {
        let root = tempfile::tempdir().unwrap();
        let proj = root.path().join("proj");
        write(
            &proj.join("lib/parse.c"),
            "#include \"../common/defs.h\"\n#include <stdio.h>\n",
        );
        write(
            &proj.join("common/defs.h"),
            "#include \"inner/limits.h\"\n#include <widget/api.h>\n",
        );
        write(&proj.join("common/inner/limits.h"), "#define CAP 4\n");
        write(&proj.join("vendor/widget/api.h"), "int copy_at(int);\n");
        write(&root.path().join("sys/stdio.h"), "");
        let mut files = BTreeSet::from([proj.join("lib/parse.c")]);
        let system = root.path().join("sys");
        let search = [proj.join("vendor"), system.clone()];
        let mut budget = ScanBudget::default();
        follow_includes(
            &mut files,
            &search,
            &|path: &Path| path.starts_with(&system),
            &mut budget,
        );
        let expected: BTreeSet<PathBuf> = [
            "lib/parse.c",
            "common/defs.h",
            "common/inner/limits.h",
            "vendor/widget/api.h",
        ]
        .iter()
        .map(|rel| proj.join(rel))
        .collect();
        assert_eq!(files, expected);
        assert!(!budget.truncated);

        // The copy stays within its budget.
        let mut files = BTreeSet::from([proj.join("lib/parse.c")]);
        let mut budget = ScanBudget {
            files: 1,
            ..ScanBudget::default()
        };
        follow_includes(&mut files, &search, &|_: &Path| false, &mut budget);
        assert_eq!(files.len(), 2, "{files:?}");
        assert!(budget.truncated);
    }

