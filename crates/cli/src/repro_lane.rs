    fn compile_line(script: &str) -> &str {
        script
            .lines()
            .find(|line| line.contains("-o poc"))
            .unwrap_or_else(|| panic!("no link line in:\n{script}"))
    }

    /// Headers keep their path relative to the include root, the include
    /// flags point at the copied roots, and spaced names stay one shell word.
    #[test]
    fn capsule_plan_keeps_include_subpaths_and_quotes_names() {
        let temp = tempfile::tempdir().unwrap();
        let harness = sample_harness(temp.path(), None);
        let plan = C_LANE
            .plan_capsule(&PlanRequest {
                harness_dir: &harness,
            })
            .unwrap();
        let shipped: Vec<&str> = plan.files.iter().map(|f| f.to.as_str()).collect();
        for expected in ["harness/main.c", "sources/inc/defs.h", "sources/rec ord.c"] {
            assert!(shipped.contains(&expected), "{expected} not in {shipped:?}");
        }
        let script = &plan.build_script;
        assert!(
            script.contains("-iquote sources -idirafter sources"),
            "{script}"
        );
        assert!(script.contains("-I harness"), "{script}");
        let link = compile_line(script);
        assert!(
            link.contains("harness/main.c 'sources/rec ord.c'"),
            "{link}"
        );
        // The shell splits the line into the expected words.
        let words = Command::new("sh")
            .arg("-c")
            .arg(format!(
                "set -- {}; for w; do printf '%s\\n' \"$w\"; done",
                link.trim().trim_start_matches("-o poc ")
            ))
            .output()
            .unwrap();
        let words = String::from_utf8_lossy(&words.stdout);
        assert!(
            words.lines().any(|word| word == "sources/rec ord.c"),
            "one shell word: {words}"
        );
        assert!(!script.contains("-DBHF_EXTERNAL_DRIVER"), "{script}");
    }

    /// The recorded recipe's standard and extra sources reach build.sh; the C
    /// standard follows the recovered flags (the Makefile's `C_STD_FLAG`
