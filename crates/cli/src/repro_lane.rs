/// Header copies when the compiler cannot list a build's includes.
const MAX_SCANNED_FILES: usize = 10_000;
const MAX_SCANNED_BYTES: u64 = 128 * 1024 * 1024;
const HEADER_EXTENSIONS: &[&str] = &[
    "h", "hh", "hpp", "hxx", "h++", "inc", "inl", "ipp", "tpp", "tcc", "def",
];
const SOURCE_EXTENSIONS: &[&str] = &["c", "cc", "cpp", "cxx", "c++", "C", "m", "mm"];

impl Lane for CFamilyLane {
    fn tag(&self) -> &'static str {
        self.tag
    }

    fn name(&self) -> &'static str {
        self.name
    }

    fn toolchain(&self) -> Toolchain {
        self.toolchain
    }

    fn recognizes(&self, harness_dir: &Path) -> bool {
        harness_dir.join(self.driver).is_file()
    }

    fn harness_problem(&self, harness_dir: &Path) -> Option<String> {
        if !harness_dir.join(self.driver).is_file() {
            return Some(format!("it has no {}", self.driver));
        }
        let Ok(text) = std::fs::read_to_string(harness_dir.join("Makefile")) else {
            return Some("it has no readable Makefile".to_owned());
        };
        if !self.parse_makefile(&text).has_main_rule {
            return Some(format!(
                "its Makefile has no `main` rule that compiles {}",
                self.driver
            ));
        }
        if read_recorded_recipe(harness_dir).is_some_and(|recipe| !recipe.native) {
            return Some(
                "it was built with a cross compiler for another target, and a capsule \
                 rebuilds for this host"
                    .to_owned(),
            );
        }
        None
    }

    fn plan_capsule(&self, request: &PlanRequest<'_>) -> anyhow::Result<CapsulePlan> {
        let model = self.build_model(request.harness_dir)?;
        self.plan_from_model(&model)
    }

    fn replay_command(&self, capsule: &Path, input: &str) -> Command {
        let mut command = Command::new("./poc");
        configure_offline_replay(&mut command);
        command.arg(input).current_dir(capsule);
        command
    }

    fn crash_signature(&self, stderr: &str, status: &ExitStatus) -> Option<String> {
        sanitizer_signature(stderr, status)
    }

    fn harness_binary(&self, work_dir: &Path, harness_id: &str) -> Option<PathBuf> {
        native_harness_binary(work_dir, harness_id)
    }
}

/// The compile inputs recovered from a C/C++ harness Makefile.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub(crate) struct MakefileFacts {
    /// Explicit target sources of the `main` rule, as written.
    pub(crate) target_sources: Vec<PathBuf>,
    /// `COMPILE_DB_FLAGS` tokens.
    pub(crate) compile_db_flags: Vec<String>,
    /// `INCLUDES` tokens (`-I .`, the C runtime, `-iquote`/`-idirafter` roots).
    pub(crate) includes: Vec<String>,
    /// The Makefile's default language standard (`CXX_STD ?= gnu++17`).
    pub(crate) default_standard: Option<String>,
    /// `BUILD_CONTEXT_LDFLAGS` tokens.
    pub(crate) link_flags: Vec<String>,
    /// Whether a `main` rule compiling the lane's driver was found.
    pub(crate) has_main_rule: bool,
}

/// The build `bhf auto` recorded for a harness (`coverage-build-recipe.json`):
/// inputs that reach `make` through the environment or the command line, not
/// the Makefile.
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize)]
struct RecordedRecipe {
    schema_version: u32,
    #[serde(default = "default_true")]
    native: bool,
    #[serde(default)]
    extra_sources: Vec<PathBuf>,
    #[serde(default)]
    extra_includes: Vec<PathBuf>,
    #[serde(default)]
    standard: Option<String>,
}

fn default_true() -> bool {
    true
}

fn read_recorded_recipe(harness_dir: &Path) -> Option<RecordedRecipe> {
    let bytes = std::fs::read(harness_dir.join(BUILD_RECIPE_FILE)).ok()?;
    let recipe: RecordedRecipe = serde_json::from_slice(&bytes).ok()?;
    (recipe.schema_version == 1).then_some(recipe)
}

/// One compiler argument, with any path it names kept apart so it can be
/// rendered for the original tree (dependency scan) or the capsule (build.sh).
#[derive(Debug, Clone, PartialEq, Eq)]
enum Arg {
    Text(String),
    /// `-I <dir>` style: flag and path as two words.
    Split(&'static str, PathBuf),
    /// `-I<dir>` style: one word.
    Joined(&'static str, PathBuf),
    /// A positional file (source, object, archive).
    File(PathBuf),
}

/// Flags whose operand is a path: include dirs first, then files.
const DIR_FLAGS: &[&str] = &["-idirafter", "-isystem", "-iquote", "-I"];
const FILE_FLAGS: &[&str] = &["-include", "-imacros"];

impl Arg {
    /// The include dir this argument adds, if it adds one.
    fn include_dir(&self) -> Option<&Path> {
        match self {
            Arg::Split(flag, path) | Arg::Joined(flag, path) if DIR_FLAGS.contains(flag) => {
                Some(path)
            }
            _ => None,
        }
    }

    fn render(&self, map: &dyn Fn(&Path) -> String) -> Vec<String> {
        match self {
            Arg::Text(text) => vec![text.clone()],
            Arg::Split(flag, path) => vec![(*flag).to_owned(), map(path)],
            Arg::Joined(flag, path) => vec![format!("{flag}{}", map(path))],
            Arg::File(path) => vec![map(path)],
        }
    }
}

/// Classify compiler tokens, resolving relative paths against `base` (the
/// directory make runs the recipe in).
fn parse_args(tokens: &[String], base: &Path) -> Vec<Arg> {
    let mut args = Vec::new();
    let mut index = 0;
    while index < tokens.len() {
        let token = &tokens[index];
        let path_flag = DIR_FLAGS
            .iter()
            .chain(FILE_FLAGS)
            .find(|flag| token.starts_with(**flag));
        match path_flag {
            Some(flag) if token == flag && index + 1 < tokens.len() => {
                args.push(Arg::Split(flag, absolute(&tokens[index + 1], base)));
                index += 2;
                continue;
            }
            // `-include` and `-imacros` take a separate word; only the
            // include-dir flags also come joined (`-I/dir`).
            Some(flag) if token.len() > flag.len() && DIR_FLAGS.contains(flag) => {
                args.push(Arg::Joined(flag, absolute(&token[flag.len()..], base)));
            }
            _ => args.push(Arg::Text(token.clone())),
        }
        index += 1;
    }
    args
}

fn absolute(raw: &str, base: &Path) -> PathBuf {
    let path = Path::new(raw);
    if path.is_absolute() {
        normalize(path)
    } else {
        normalize(&base.join(path))
    }
}

/// Lexically drop `.` and resolve `..` (no symlink resolution: a capsule
/// mirrors the paths the build used).
pub(crate) fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                if !out.pop() {
                    out.push("..");
                }
            }
            other => out.push(other.as_os_str()),
        }
    }
    out
}

/// One translation unit `bhf auto` compiles separately with its own
/// compile-database flags (`build_context_objects.mk`,
/// `repair_context_objects.mk`).
#[derive(Debug, Clone, PartialEq, Eq)]
struct Unit {
    source: PathBuf,
    flags: Vec<Arg>,
}

/// Everything needed to rebuild one harness, with original absolute paths.
struct BuildModel {
    harness_dir: PathBuf,
    driver: PathBuf,
    target_sources: Vec<PathBuf>,
    extra_sources: Vec<PathBuf>,
    units: Vec<Unit>,
    compile_db_flags: Vec<Arg>,
    includes: Vec<Arg>,
    extra_includes: Vec<Arg>,
    standard: Option<String>,
    compat_flags: Vec<String>,
    link_flags: Vec<Arg>,
    recorded_recipe: bool,
    warnings: Vec<String>,
}

impl CFamilyLane {
    pub(crate) fn parse_makefile(&self, text: &str) -> MakefileFacts {
        let mut facts = MakefileFacts::default();
        let mut in_main = false;
        let standard_default = format!("{} ?=", self.standard_var);
        for line in text.lines() {
            if let Some(rest) = line.strip_prefix("COMPILE_DB_FLAGS =") {
                facts.compile_db_flags = crate::generate_harness::split_compile_command(rest);
            } else if let Some(rest) = line.strip_prefix("INCLUDES =") {
                facts.includes = crate::generate_harness::split_compile_command(rest);
            } else if let Some(rest) = line.strip_prefix("BUILD_CONTEXT_LDFLAGS =") {
                facts.link_flags = crate::generate_harness::split_compile_command(rest);
            } else if let Some(rest) = line.strip_prefix(&standard_default) {
                facts.default_standard = Some(rest.trim().to_owned()).filter(|s| !s.is_empty());
            }
            if line.starts_with("main:") {
                in_main = true;
                continue;
            }
            if !in_main {
                continue;
            }
            if !line.starts_with('\t') {
                in_main = line.trim().is_empty();
                continue;
            }
            in_main = false;
            // `$(CXX) ... -o $@ main.cpp <sources> $(CONTEXT_MAIN_OBJECTS) ...`:
            // the explicit target sources sit between the driver and the first
            // make variable. Match the driver as a whole word: `main.c` is a
            // prefix of `main.cpp`.
            let tokens = crate::generate_harness::split_compile_command(line.trim());
            let Some(at) = tokens
                .windows(3)
                .position(|w| w[0] == "-o" && w[1] == "$@" && w[2] == self.driver)
            else {
                continue;
            };
            facts.has_main_rule = true;
            facts.target_sources = tokens[at + 3..]
                .iter()
                .take_while(|token| !token.starts_with("$("))
                .map(PathBuf::from)
                .collect();
        }
        facts
    }

    fn build_model(&self, harness_dir: &Path) -> anyhow::Result<BuildModel> {
        let harness_dir = normalize(&std::path::absolute(harness_dir)?);
        let makefile = harness_dir.join("Makefile");
        let text = std::fs::read_to_string(&makefile)
            .map_err(|error| anyhow::anyhow!("cannot read {}: {error}", makefile.display()))?;
        let facts = self.parse_makefile(&text);
        if !facts.has_main_rule {
            anyhow::bail!(
                "{} has no `main` rule that compiles {}",
                makefile.display(),
                self.driver
            );
        }
        let recipe = read_recorded_recipe(&harness_dir);
        let repairs = harness_dir.join("repairs");
        let mut warnings = Vec::new();
        let units = per_translation_units(&harness_dir, &mut warnings);
        let unit_sources: BTreeSet<PathBuf> = units.iter().map(|u| u.source.clone()).collect();
        let target_sources: Vec<PathBuf> = facts
            .target_sources
            .iter()
            .map(|source| absolute(&source.to_string_lossy(), &harness_dir))
            .collect();
        // With a recorded recipe, its extra sources are exactly what the build
        // linked (repair stubs included); without one, ship the repair stubs.
        let candidates = match &recipe {
            Some(recipe) => recipe.extra_sources.clone(),
            None => self.repair_stub_sources(&repairs),
        };
        let mut seen: BTreeSet<PathBuf> = target_sources.iter().cloned().collect();
        seen.extend(unit_sources);
        let mut extra_sources = Vec::new();
        for source in candidates {
            let source = absolute(&source.to_string_lossy(), &harness_dir);
            if is_provenance_stub(&source) || !seen.insert(source.clone()) {
                continue;
            }
            extra_sources.push(source);
        }
        let mut extra_includes = Vec::new();
        for name in [
            crate::auto::repair::AUTO_CPP_INCLUDES_FILE,
            crate::auto::repair::AUTO_DEFINES_FILE,
        ] {
            let header = repairs.join(name);
            if header.is_file() {
                extra_includes.push(Arg::Split("-include", header));
            }
        }
        if let Some(recipe) = &recipe {
            for dir in &recipe.extra_includes {
                let dir = absolute(&dir.to_string_lossy(), &harness_dir);
                extra_includes.push(Arg::Split("-iquote", dir.clone()));
                extra_includes.push(Arg::Split("-idirafter", dir));
            }
        }
        let compat_flags = if self.standard_leads {
            Vec::new()
        } else {
            read_compat_flags(&harness_dir)
        };
        let mut link_flags = Vec::new();
        for arg in parse_args(&facts.link_flags, &harness_dir) {
            // A prebuilt object or archive named by path ships with the capsule.
            match arg {
                Arg::Text(text) if !text.starts_with('-') => {
                    let path = absolute(&text, &harness_dir);
                    link_flags.push(if path.is_file() {
                        Arg::File(path)
                    } else {
                        Arg::Text(text)
                    });
                }
                other => link_flags.push(other),
            }
        }
        Ok(BuildModel {
            driver: harness_dir.join(self.driver),
            compile_db_flags: parse_args(&facts.compile_db_flags, &harness_dir),
            includes: parse_args(&facts.includes, &harness_dir),
            standard: recipe
                .as_ref()
                .and_then(|recipe| recipe.standard.clone())
                .filter(|standard| !standard.trim().is_empty())
                .or(facts.default_standard),
            recorded_recipe: recipe.is_some(),
            harness_dir,
            target_sources,
            extra_sources,
            units,
            extra_includes,
            compat_flags,
            link_flags,
            warnings,
        })
    }

    fn repair_stub_sources(&self, repairs: &Path) -> Vec<PathBuf> {
        let mut sources: Vec<PathBuf> = std::fs::read_dir(repairs)
            .into_iter()
            .flatten()
            .flatten()
            .map(|entry| entry.path())
            .filter(|path| {
                path.is_file()
                    && path
                        .extension()
                        .and_then(|ext| ext.to_str())
                        .is_some_and(|ext| self.stub_extensions.contains(&ext))
            })
            .collect();
        sources.sort();
        sources
    }

    /// The flags every compile of this lane starts with, through the language
    /// standard when it leads.
    fn leading_flags(&self, standard: Option<&str>) -> Vec<String> {
        let mut flags: Vec<String> = SANITIZER_FLAGS.iter().map(|f| (*f).to_owned()).collect();
        if self.standard_leads {
            if let Some(standard) = standard {
                flags.push(format!("-std={standard}"));
            }
        }
        flags.extend(self.lane_flags.iter().map(|f| (*f).to_owned()));
        flags.extend(SECTION_FLAGS.iter().map(|f| (*f).to_owned()));
        flags
    }

    /// The full argument list (no output, no inputs) of the `main` compile.
    fn main_args(&self, model: &BuildModel, map: &dyn Fn(&Path) -> String) -> Vec<String> {
        let mut args = self.leading_flags(model.standard.as_deref());
        args.extend(model.compat_flags.iter().cloned());
        args.extend(FEATURE_TEST_FLAGS.iter().map(|f| (*f).to_owned()));
        args.extend(model.compile_db_flags.iter().flat_map(|a| a.render(map)));
        if !self.standard_leads {
            if let Some(standard) = &model.standard {
                args.push(format!("-std={standard}"));
            }
        }
        args.extend(model.includes.iter().flat_map(|a| a.render(map)));
        args.extend(model.extra_includes.iter().flat_map(|a| a.render(map)));
        args
    }

    /// The argument list (no output, no input) of one per-TU compile.
    fn unit_args(
        &self,
        model: &BuildModel,
        unit: &Unit,
        map: &dyn Fn(&Path) -> String,
    ) -> Vec<String> {
        let mut args = self.leading_flags(model.standard.as_deref());
        args.extend(model.compat_flags.iter().cloned());
        args.extend(unit.flags.iter().flat_map(|a| a.render(map)));
        args.extend(model.includes.iter().flat_map(|a| a.render(map)));
        args.extend(model.extra_includes.iter().flat_map(|a| a.render(map)));
        args
    }

    fn plan_from_model(&self, model: &BuildModel) -> anyhow::Result<CapsulePlan> {
        let mut warnings = model.warnings.clone();
        let explicit = std::iter::once(&model.driver)
            .chain(&model.target_sources)
            .chain(&model.extra_sources)
            .chain(model.units.iter().map(|unit| &unit.source));
        for path in explicit {
            if !path.is_file() {
                anyhow::bail!(
                    "{} is part of the harness build but no longer exists",
                    path.display()
                );
            }
        }
        let compiler = self.toolchain.compiler();
        // A clang++ that picked a GCC install without its libstdc++ headers
        // cannot compile `<string>`; bhf's C++ builds then add the newest
        // installed libstdc++ headers (crate::build), and so does the scan.
        let stdlib_flags = if self.recovers_cpp_stdlib {
            crate::build::detect_cpp_stdlib_include_flags_for(&compiler, &[])
        } else {
            Vec::new()
        };
        let system = system_include_dirs(&compiler, self.probe_language);
        let is_system = |path: &Path| system.iter().any(|dir| path.starts_with(dir));
        let original = |path: &Path| path.to_string_lossy().into_owned();

        // 1. The files the build reads: its inputs plus the include closure the
        //    compiler reports (`-M` lists every header a TU includes, however
        //    deep and through whichever include root).
        let mut files: BTreeSet<PathBuf> = BTreeSet::new();
        files.insert(model.driver.clone());
        files.extend(model.target_sources.iter().cloned());
        files.extend(model.extra_sources.iter().cloned());
        files.extend(model.units.iter().map(|u| u.source.clone()));
        for arg in model.extra_includes.iter().chain(&model.compile_db_flags) {
            if let Arg::Split("-include" | "-imacros", path) = arg {
                files.insert(path.clone());
            }
        }
        files.extend(model.link_flags.iter().filter_map(|a| match a {
            Arg::File(path) => Some(path.clone()),
            _ => None,
        }));
        let main_inputs: Vec<PathBuf> = std::iter::once(model.driver.clone())
            .chain(model.target_sources.iter().cloned())
            .chain(model.extra_sources.iter().cloned())
            .filter(|path| has_extension(path, SOURCE_EXTENSIONS))
            .collect();
        let mut scans = vec![(self.main_args(model, &original), main_inputs)];
        for unit in &model.units {
            scans.push((
                self.unit_args(model, unit, &original),
                vec![unit.source.clone()],
            ));
        }
        let mut closure = "compiler";
        for (args, inputs) in &mut scans {
            args.extend(stdlib_flags.iter().cloned());
            match dependency_closure(&compiler, &model.harness_dir, args, inputs) {
                Some(deps) => files.extend(deps.into_iter().filter(|dep| !is_system(dep))),
                None => closure = "header-scan",
            }
        }

        // 2. Where each file goes. The harness dir, its repairs and the C
        //    runtime have fixed homes; every other file keeps its path relative
        //    to the deepest dir holding all of them (and every project include
        //    root), so `#include "sub/x.h"` and `"../x.h"` still resolve.
        let repairs = model.harness_dir.join("repairs");
        let runtime_dirs: Vec<PathBuf> = model
            .includes
            .iter()
            .filter_map(Arg::include_dir)
            .filter(|dir| dir.join("bhf_decode.h").is_file())
            .map(Path::to_path_buf)
            .collect();
        let mut mounts: Vec<(PathBuf, String)> = vec![
            (repairs.clone(), "stubs".to_owned()),
            (model.harness_dir.clone(), "harness".to_owned()),
        ];
        for (index, dir) in runtime_dirs.iter().enumerate() {
            let name = if index == 0 {
                "runtime".to_owned()
            } else {
                format!("runtime_{index}")
            };
            mounts.push((dir.clone(), name));
        }
        let fixed = |path: &Path| mounts.iter().any(|(dir, _)| path.starts_with(dir));
        let project_roots: Vec<PathBuf> = model
            .includes
            .iter()
            .chain(&model.extra_includes)
            .chain(&model.compile_db_flags)
            .chain(model.units.iter().flat_map(|u| &u.flags))
            .filter_map(Arg::include_dir)
            .filter(|dir| dir.is_dir() && !is_system(dir) && !fixed(dir))
            .map(Path::to_path_buf)
            .collect();
        if closure == "header-scan" {
            let mut budget = ScanBudget::default();
            let mut roots: Vec<PathBuf> = project_roots.clone();
            roots.extend(
                files
                    .iter()
                    .filter(|path| !fixed(path))
                    .filter_map(|path| path.parent().map(Path::to_path_buf)),
            );
            roots.push(repairs.clone());
            roots.extend(runtime_dirs.iter().cloned());
            roots.sort();
            roots.dedup();
            for root in &roots {
                scan_headers(root, &model.harness_dir, &mut budget, &mut files);
            }
            scan_shallow_headers(&model.harness_dir, &mut files);
            // A header outside every root (`#include "../common/defs.h"`) is
            // found by following the include lines themselves.
            let search: Vec<PathBuf> = model
                .includes
                .iter()
                .chain(&model.extra_includes)
                .chain(&model.compile_db_flags)
                .chain(model.units.iter().flat_map(|u| &u.flags))
                .filter_map(Arg::include_dir)
                .filter(|dir| dir.is_dir() && !is_system(dir))
                .map(Path::to_path_buf)
                .collect();
            follow_includes(&mut files, &search, &is_system, &mut budget);
            if budget.truncated {
                warnings.push(format!(
                    "the compiler could not list the build's includes, and the header copy \
                     stopped at {MAX_SCANNED_FILES} files / {} MiB",
                    MAX_SCANNED_BYTES / (1024 * 1024)
                ));
            } else {
                warnings.push(
                    "the compiler could not list the build's includes; every header under \
                     the include roots was copied instead"
                        .to_owned(),
                );
            }
        }
        let project_files: Vec<&PathBuf> = files
            .iter()
            .filter(|path| !fixed(path) && !is_system(path))
            .collect();
        let anchors = project_files
            .iter()
            .filter_map(|path| path.parent())
            .chain(project_roots.iter().map(PathBuf::as_path));
        if let Some(root) = common_ancestor(anchors) {
            mounts.push((root, "sources".to_owned()));
        }
        // Longest prefix wins: `repairs/` inside the harness dir, a harness dir
        // inside the project tree.
        mounts.sort_by_key(|(dir, _)| std::cmp::Reverse(dir.components().count()));
        let place = |path: &Path| -> Option<String> {
            mounts.iter().find_map(|(dir, name)| {
                let rel = path.strip_prefix(dir).ok()?;
                let rel = rel.to_string_lossy().replace('\\', "/");
                Some(if rel.is_empty() {
                    name.clone()
                } else {
                    format!("{name}/{rel}")
                })
            })
        };
        let capsule_path = |path: &Path| -> String {
            if is_system(path) {
                return original(path);
            }
            place(path).unwrap_or_else(|| original(path))
        };

        let mut copies = Vec::new();
        for path in &files {
            if is_system(path) || !path.is_file() {
                continue;
            }
            match place(path) {
                Some(to) => copies.push(CapsuleFile {
                    from: path.clone(),
                    to,
                }),
                None => warnings.push(format!("{} has no place in the capsule", path.display())),
            }
        }

        // 3. build.sh: per-TU objects first, then the `main` link, all relative.
        let compiler_var = self.toolchain.env_var;
        let mut script = format!(
            "#!/bin/sh\n\
             # Rebuild this bhf PoC offline. Needs only {} and a shell.\n\
             set -e\n\
             cd \"$(dirname \"$0\")\"\n\
             {compiler_var}=\"${{{compiler_var}:-{}}}\"\n\
             case \"$(uname -s)\" in\n\
             \x20 Darwin) GC_LDFLAGS=-Wl,-dead_strip ;;\n\
             \x20 *) GC_LDFLAGS=-Wl,--gc-sections ;;\n\
             esac\n",
            self.toolchain.describe(),
            self.toolchain.default,
        );
        let (stdlib_cflags, stdlib_ldflags) = if self.recovers_cpp_stdlib {
            script.push_str(&cpp_stdlib_fallback(compiler_var));
            (" $STDLIB_FLAGS", " $STDLIB_LDFLAGS")
        } else {
            ("", "")
        };
        let mut objects = Vec::new();
        if !model.units.is_empty() {
            script.push_str("mkdir -p obj\n");
        }
        for (index, unit) in model.units.iter().enumerate() {
            let object = format!("obj/unit_{index}.o");
            let args = shell_words(&self.unit_args(model, unit, &capsule_path));
            script.push_str(&format!(
                "\"${compiler_var}\" {args}{stdlib_cflags} \\\n\x20 -c {} -o {object}\n",
                sh_word(&capsule_path(&unit.source))
            ));
            objects.push(object);
        }
        let mut inputs = vec![capsule_path(&model.driver)];
        inputs.extend(model.target_sources.iter().map(|p| capsule_path(p)));
        inputs.extend(objects);
        inputs.extend(model.extra_sources.iter().map(|p| capsule_path(p)));
        let link: Vec<String> = model
            .link_flags
            .iter()
            .flat_map(|a| a.render(&capsule_path))
            .collect();
        script.push_str(&format!(
            "\"${compiler_var}\" {}{stdlib_cflags} \\\n\x20 -o poc {} $GC_LDFLAGS{stdlib_ldflags}{}\n",
            shell_words(&self.main_args(model, &capsule_path)),
            shell_words(&inputs),
            if link.is_empty() {
                String::new()
            } else {
                format!(" {}", shell_words(&link))
            },
        ));

        let mut layout = vec![(
            format!("harness/{}", self.driver),
            "the fuzz driver (decodes the input, calls the target)".to_owned(),
        )];
        let has = |prefix: &str| copies.iter().any(|c| c.to.starts_with(prefix));
        if has("sources/") {
            layout.push((
                "sources/".to_owned(),
                "the target sources and the project headers they include, in their original \
                 layout"
                    .to_owned(),
            ));
        }
        if has("stubs/") {
            layout.push((
                "stubs/".to_owned(),
                "the stubs and placeholder headers bhf synthesized to make the tree build"
                    .to_owned(),
            ));
        }
        if has("runtime") {
            layout.push((
                "runtime/".to_owned(),
                "the bhf decode-runtime headers".to_owned(),
            ));
        }
        Ok(CapsulePlan {
            build_facts: json!({
                "compiler_env": compiler_var,
                "default_compiler": self.toolchain.default,
                "standard": model.standard,
                "recorded_recipe": model.recorded_recipe,
                "extra_sources": model.extra_sources.len(),
                "translation_units": model.units.len(),
                "include_closure": closure,
                "stdlib_include_fallback": !stdlib_flags.is_empty(),
            }),
            files: copies,
            build_script: script,
            layout,
            build_outputs: vec!["poc", "obj"],
            warnings,
        })
    }
}

fn has_extension(path: &Path, extensions: &[&str]) -> bool {
    path.extension()
        .and_then(|ext| ext.to_str())
        .is_some_and(|ext| extensions.contains(&ext))
}

fn is_provenance_stub(path: &Path) -> bool {
    path.file_stem()
        .and_then(|stem| stem.to_str())
        .is_some_and(|stem| stem == PROVENANCE_STUBS)
}

/// `C_COMPAT_FLAGS` from the work dir's `c_compat.mk`, which every C harness
/// Makefile includes as `../../c_compat.mk` (written when legacy tentative
/// definitions need `-fcommon`).
fn read_compat_flags(harness_dir: &Path) -> Vec<String> {
    let Some(work_dir) = harness_dir.parent().and_then(Path::parent) else {
        return Vec::new();
    };
    let Ok(text) = std::fs::read_to_string(work_dir.join("c_compat.mk")) else {
        return Vec::new();
    };
    // The last assignment wins, as in make.
    text.lines()
        .rev()
        .find_map(|line| {
            let rest = line.strip_prefix("C_COMPAT_FLAGS")?;
            let rest = rest.trim_start();
            let rest = rest
                .strip_prefix(":=")
                .or_else(|| rest.strip_prefix("?="))
                .or_else(|| rest.strip_prefix('='))?;
            Some(crate::generate_harness::split_compile_command(rest))
        })
        .unwrap_or_default()
}

/// The `main`-variant per-translation-unit rules of a harness:
/// `<dir>/main_<n>.o: ...` followed by `<compiler> $(CFLAGS) $(SECTION_FLAGS)
/// [$(C_COMPAT_FLAGS)] <flags> $(INCLUDES) ... -c <source> -o <object>`.
fn per_translation_units(harness_dir: &Path, warnings: &mut Vec<String>) -> Vec<Unit> {
    let mut units = Vec::new();
    for fragment in ["build_context_objects.mk", "repair_context_objects.mk"] {
        let Ok(text) = std::fs::read_to_string(harness_dir.join(fragment)) else {
            continue;
        };
        let mut lines = text.lines().peekable();
        while let Some(line) = lines.next() {
            let Some((target, _)) = line.split_once(':') else {
                continue;
            };
            let is_main_object = target
                .rsplit('/')
                .next()
                .is_some_and(|name| name.starts_with("main_") && name.ends_with(".o"));
            if !is_main_object || line.starts_with('\t') {
                continue;
            }
            let recipe = lines
                .by_ref()
                .take_while(|next| next.starts_with('\t'))
                .find(|next| next.contains(" -c "));
            let parsed = recipe.and_then(|recipe| {
                let tokens = crate::generate_harness::split_compile_command(recipe.trim());
                let start = tokens
                    .iter()
                    .position(|t| t == "$(SECTION_FLAGS)")
                    .map(|i| i + 1)?;
                let start = if tokens.get(start).map(String::as_str) == Some("$(C_COMPAT_FLAGS)") {
                    start + 1
                } else {
                    start
                };
                let end = tokens.iter().position(|t| t == "$(INCLUDES)")?;
                let source = tokens
                    .iter()
                    .position(|t| t == "-c")
                    .and_then(|i| tokens.get(i + 1))?;
                (start <= end).then(|| Unit {
                    source: absolute(source, harness_dir),
                    flags: parse_args(&tokens[start..end], harness_dir),
                })
            });
            match parsed {
                Some(unit) => units.push(unit),
                None => warnings.push(format!(
                    "could not read the per-translation-unit rule for {target} in {fragment}; \
                     the capsule may not link"
                )),
            }
        }
    }
    units
}

/// Where system files live, never copied into a capsule: the compiler's
/// builtin `#include <...>` search dirs and its resource dir (sanitizer
/// ignore lists are build dependencies too), plus the conventional system
/// prefixes as a fallback.
fn system_include_dirs(compiler: &str, language: &str) -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = [
        "/usr/include",
        "/usr/local/include",
        "/usr/lib",
        "/usr/share",
        "/lib",
    ]
    .iter()
    .map(PathBuf::from)
    .collect();
    let mut resource = Command::new(compiler);
    resource.arg("-print-resource-dir");
    if let Ok(output) =
        crate::command_output::output_with_timeout(&mut resource, Duration::from_secs(30))
    {
        let dir = String::from_utf8_lossy(&output.stdout).trim().to_owned();
        if output.status.success() && !dir.is_empty() && Path::new(&dir).is_dir() {
            dirs.push(normalize(Path::new(&dir)));
        }
    }
    let mut command = Command::new(compiler);
    command
        .args(["-E", "-x", language, "-", "-v"])
        .stdin(std::process::Stdio::null());
    if let Ok(output) =
        crate::command_output::output_with_timeout(&mut command, Duration::from_secs(30))
    {
        let stderr = String::from_utf8_lossy(&output.stderr);
        let mut inside = false;
        for line in stderr.lines() {
            if line.starts_with("#include <...> search starts here:") {
                inside = true;
            } else if line.starts_with("End of search list.") {
                inside = false;
            } else if inside {
                let dir = line.trim().trim_end_matches(" (framework directory)");
                if !dir.is_empty() {
                    dirs.push(normalize(Path::new(dir)));
                }
            }
        }
    }
    dirs
}

/// Every file `inputs` read when compiled with `args`, from the compiler's own
/// dependency output (`-M`). `None` when the compiler could not produce it.
fn dependency_closure(
    compiler: &str,
    cwd: &Path,
    args: &[String],
    inputs: &[PathBuf],
) -> Option<Vec<PathBuf>> {
    if inputs.is_empty() {
        return Some(Vec::new());
    }
    let mut command = Command::new(compiler);
    command
        .args(args)
        .args(["-M", "-w"])
        .args(inputs)
        .current_dir(cwd);
    let output =
        crate::command_output::output_with_timeout(&mut command, Duration::from_secs(300)).ok()?;
    if !output.status.success() {
        return None;
    }
    Some(
        parse_make_dependencies(&String::from_utf8_lossy(&output.stdout))
            .into_iter()
            .map(|dep| absolute(&dep, cwd))
            .collect(),
    )
}

/// The prerequisites of make-format dependency rules (`a.o: a.c x.h \`).
/// Spaces in paths are `\ `-escaped, `#` is `\#`, `$` is `$$`.
fn parse_make_dependencies(text: &str) -> Vec<String> {
    let joined = text.replace("\\\r\n", " ").replace("\\\n", " ");
    let mut deps = Vec::new();
    for line in joined.lines() {
        let Some((_, prerequisites)) = line.split_once(": ") else {
            continue;
        };
        let mut current = String::new();
        let mut chars = prerequisites.chars().peekable();
        while let Some(c) = chars.next() {
            match c {
                '\\' if matches!(chars.peek(), Some(' ' | '#' | '\\')) => {
                    current.push(chars.next().unwrap_or(' '));
                }
                '$' if chars.peek() == Some(&'$') => {
                    chars.next();
                    current.push('$');
                }
                c if c.is_whitespace() => {
                    if !current.is_empty() {
                        deps.push(std::mem::take(&mut current));
                    }
                }
                c => current.push(c),
            }
        }
        if !current.is_empty() {
            deps.push(current);
        }
    }
    deps
}

#[derive(Debug)]
struct ScanBudget {
    files: usize,
    bytes: u64,
    truncated: bool,
}

impl Default for ScanBudget {
    fn default() -> Self {
        Self {
            files: MAX_SCANNED_FILES,
            bytes: MAX_SCANNED_BYTES,
            truncated: false,
        }
    }
}

/// Every header under `root`, recursively (skipping VCS dirs and the harness
/// dir, which has its own home), within `budget`.
fn scan_headers(
    root: &Path,
    harness_dir: &Path,
    budget: &mut ScanBudget,
    out: &mut BTreeSet<PathBuf>,
) {
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        let mut entries: Vec<_> = entries.flatten().map(|e| e.path()).collect();
        entries.sort();
        for path in entries {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if path.is_dir() {
                let skip = matches!(name, ".git" | ".hg" | ".svn" | "node_modules")
                    || (path.starts_with(harness_dir)
                        && !path.starts_with(harness_dir.join("repairs")));
                if !skip && !path.is_symlink() {
                    stack.push(path);
                }
                continue;
            }
            if !has_extension(&path, HEADER_EXTENSIONS) || out.contains(&path) {
                continue;
            }
            let size = std::fs::metadata(&path).map(|m| m.len()).unwrap_or(0);
            if budget.files == 0 || budget.bytes < size {
                budget.truncated = true;
                return;
            }
            budget.files -= 1;
            budget.bytes -= size;
            out.insert(normalize(&path));
        }
    }
}

/// Add, transitively, the project files the sources and headers in `files`
/// include: a quoted name resolves against the including file's dir first,
/// then (like an angled one) against `search`; system files are left out.
/// Within `budget`.
fn follow_includes(
    files: &mut BTreeSet<PathBuf>,
    search: &[PathBuf],
    is_system: &dyn Fn(&Path) -> bool,
    budget: &mut ScanBudget,
) {
    let readable = |path: &Path| {
        has_extension(path, HEADER_EXTENSIONS) || has_extension(path, SOURCE_EXTENSIONS)
    };
    let mut queue: Vec<PathBuf> = files.iter().filter(|p| readable(p)).cloned().collect();
    let mut read = BTreeSet::new();
    while let Some(file) = queue.pop() {
        if !read.insert(file.clone()) {
            continue;
        }
        let Ok(bytes) = std::fs::read(&file) else {
            continue;
        };
        let text = String::from_utf8_lossy(&bytes);
        let dir = file.parent().map(Path::to_path_buf).unwrap_or_default();
        for (name, quoted) in include_directives(&text) {
            let found = quoted
                .then(|| dir.join(name))
                .into_iter()
                .chain(search.iter().map(|root| root.join(name)))
                .map(|path| normalize(&path))
                .find(|path| path.is_file());
            let Some(found) = found else {
                continue;
            };
            if is_system(&found) || files.contains(&found) {
                continue;
            }
            let size = std::fs::metadata(&found).map(|m| m.len()).unwrap_or(0);
            if budget.files == 0 || budget.bytes < size {
                budget.truncated = true;
                return;
            }
            budget.files -= 1;
            budget.bytes -= size;
            files.insert(found.clone());
            if readable(&found) {
                queue.push(found);
            }
        }
    }
}

/// The `#include` / `#import` names in `text`, each with whether it is quoted
/// (`"x.h"`) rather than angled (`<x.h>`).
fn include_directives(text: &str) -> Vec<(&str, bool)> {
    text.lines()
        .filter_map(|line| {
            let rest = line.trim_start().strip_prefix('#')?.trim_start();
            let rest = rest
                .strip_prefix("include")
                .or_else(|| rest.strip_prefix("import"))?
                .trim_start();
            let (close, quoted) = match rest.chars().next()? {
                '"' => ('"', true),
                '<' => ('>', false),
                _ => return None,
            };
            let body = &rest[1..];
            let name = &body[..body.find(close)?];
            (!name.is_empty()).then_some((name, quoted))
        })
        .collect()
}

/// The `build.sh` lines that recover the C++ standard library when
/// `$<compiler_var>` cannot find it itself (some clang++ installs pick a GCC
/// whose libstdc++ is missing): the newest installed libstdc++ headers that
/// make `<string>` compile, and the dir holding `libstdc++.so` for the link.
/// They are probed on the host that runs the script, so nothing host-specific
/// is recorded.
fn cpp_stdlib_fallback(compiler_var: &str) -> String {
    format!(
        "# Recover the C++ standard library when ${compiler_var} cannot find it itself.\n\
         STDLIB_FLAGS=\n\
         STDLIB_LDFLAGS=\n\
         cxx_has_stdlib() {{ printf '#include <string>\\n' | \"${compiler_var}\" \"$@\" -x c++ -fsyntax-only - >/dev/null 2>&1; }}\n\
         if ! cxx_has_stdlib; then\n\
         \x20 for v in $(ls /usr/include/c++ 2>/dev/null | sort -rn); do\n\
         \x20   [ -f \"/usr/include/c++/$v/string\" ] || continue\n\
         \x20   flags=\"-isystem /usr/include/c++/$v\"\n\
         \x20   for d in /usr/include/*/c++/$v /usr/include/c++/$v/backward; do\n\
         \x20     if [ -d \"$d\" ]; then flags=\"$flags -isystem $d\"; fi\n\
         \x20   done\n\
         \x20   if cxx_has_stdlib $flags; then STDLIB_FLAGS=$flags; break; fi\n\
         \x20 done\n\
         fi\n\
         case \"$(\"${compiler_var}\" -print-file-name=libstdc++.so 2>/dev/null)\" in\n\
         \x20 /*) ;;\n\
         \x20 *) for d in $(ls -d /usr/lib/gcc/*/* 2>/dev/null | sort -t/ -k6,6n); do\n\
         \x20      if [ -f \"$d/libstdc++.so\" ]; then STDLIB_LDFLAGS=\"-L$d\"; fi\n\
         \x20    done ;;\n\
         esac\n"
    )
}

/// The headers directly in `dir`.
fn scan_shallow_headers(dir: &Path, out: &mut BTreeSet<PathBuf>) {
    for entry in std::fs::read_dir(dir).into_iter().flatten().flatten() {
        let path = entry.path();
        if path.is_file() && has_extension(&path, HEADER_EXTENSIONS) {
            out.insert(normalize(&path));
        }
    }
}

/// The deepest directory containing every path in `dirs`.
fn common_ancestor<'a>(dirs: impl Iterator<Item = &'a Path>) -> Option<PathBuf> {
    let mut common: Option<PathBuf> = None;
    for dir in dirs {
        common = Some(match common {
            None => dir.to_path_buf(),
            Some(mut acc) => {
                while !dir.starts_with(&acc) {
                    if !acc.pop() {
                        break;
                    }
                }
                acc
            }
        });
    }
    common
}

