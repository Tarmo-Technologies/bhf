//! COBOL and Fortran: harnesses bhf links on its C path.
//!
//! A COBOL harness is bhf's C driver (`main.c`) with the program translated to
//! C by `cobc -C` (`cobol_target.c`) and a glue that calls it; a Fortran
//! harness is the same driver with the routine compiled by `gfortran` and a
//! glue that calls it through the gfortran C ABI. Both build from the harness
//! Makefile like a C harness, so their capsules are C capsules plus:
//!
//! - COBOL: the GnuCOBOL runtime on the link (`cob-config --libs`, probed by
//!   build.sh on the host that runs it), the COBOL source beside its
//!   translation, and libcob's own runtime check as the crash oracle (`libcob:
//!   <file>:<line>: error: <what>`).
//! - Fortran: every Fortran object of the link compiled from the shipped
//!   source with the flags bhf recorded (`fortran-build.json`), then the
//!   gfortran runtime on the link.

use super::{CFamilyLane, HarnessContext, RebuiltObject, Toolchain};
use serde_json::{json, Value};
use std::path::PathBuf;

/// The language glue of a harness linked on the C path.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Glue {
    Cobol,
    Fortran,
}

impl Glue {
    /// The glue file bhf writes beside `main.c`.
    pub(crate) fn glue_file(self) -> &'static str {
        match self {
            Glue::Cobol => "cobol_glue.c",
            Glue::Fortran => "fortran_glue.c",
        }
    }
}

/// The sidecar the Fortran lane writes: how each Fortran object of the link
/// was compiled.
pub(crate) const FORTRAN_BUILD_RECORD: &str = "fortran-build.json";

const COBOL_TOOLS: &[Toolchain] = &[Toolchain::new(
    "CC",
    "clang",
    "compiles the driver and the translated COBOL program (with libcob, the GnuCOBOL runtime)",
)];
const FORTRAN_TOOLS: &[Toolchain] = &[
    Toolchain::new("CC", "clang", "compiles and links the driver"),
    Toolchain::new("FC", "gfortran", "compiles the Fortran sources"),
];

pub(crate) static COBOL_LANE: CFamilyLane = CFamilyLane {
    tag: "cobol",
    name: "COBOL",
    driver: "main.c",
    tools: COBOL_TOOLS,
    standard_var: "C_STD",
    standard_leads: false,
    clang_lane_flags: &[],
    probe_language: "c",
    stub_extensions: &["c"],
    recovers_cpp_stdlib: false,
    glue: Some(Glue::Cobol),
};

pub(crate) static FORTRAN_LANE: CFamilyLane = CFamilyLane {
    tag: "fortran",
    name: "Fortran",
    driver: "main.c",
    tools: FORTRAN_TOOLS,
    standard_var: "C_STD",
    standard_leads: false,
    clang_lane_flags: &[],
    probe_language: "c",
    stub_extensions: &["c"],
    recovers_cpp_stdlib: false,
    glue: Some(Glue::Fortran),
};

/// Add the language runtime and sources to a C build model.
pub(crate) fn adjust_model(
    glue: Glue,
    harness: &HarnessContext,
    model: &mut super::BuildModel,
) -> anyhow::Result<()> {
    // The glue marks the target's entry for the fuzz loop through the driver
    // object bhf links (`bhf_target_enter`); a replay links no such object, so
    // the capsule gives it a no-op.
    model.generated_sources.push((
        "stubs/bhf_capsule_entry.c".to_owned(),
        "/* Generated by bhf capsule: the target-entry mark the glue calls; a replay\n \
         * does not track it. */\n\
         __attribute__((weak)) void bhf_target_enter(void) {}\n"
            .to_owned(),
    ));
    match glue {
        Glue::Cobol => {
            model.prelude.push_str(
                "# The GnuCOBOL runtime the translated program links against.\n\
                 COB_LIBS=$(cob-config --libs 2>/dev/null) || COB_LIBS=\n\
                 if [ -z \"$COB_LIBS\" ]; then COB_LIBS=\"-lcob -lm\"; fi\n",
            );
            model.extra_link.push("$COB_LIBS".to_owned());
            let source = super::recorded_target_source(&harness.work_dir, &harness.harness_id)
                .filter(|source| source.is_file());
            model.facts.insert(
                "cobol_translation".to_owned(),
                json!("harness/cobol_target.c (cobc -C -debug -fec=all)"),
            );
            if let Some(source) = source {
                model.extra_files.push(source);
            }
        }
        Glue::Fortran => {
            model.prelude.push_str(
                "FC=\"${FC:-gfortran}\"\n\
                 # The gfortran runtime the Fortran objects link against.\n\
                 FORTRAN_LIBDIR=$(dirname \"$(\"$FC\" -print-file-name=libgfortran.so 2>/dev/null)\")\n\
                 FORTRAN_LIBS=\"-lgfortran -lquadmath -lm\"\n\
                 if [ -d \"$FORTRAN_LIBDIR\" ] && [ \"$FORTRAN_LIBDIR\" != . ]; then \
                 FORTRAN_LIBS=\"-L$FORTRAN_LIBDIR $FORTRAN_LIBS\"; fi\n",
            );
            model.extra_link.push("$FORTRAN_LIBS".to_owned());
            match read_fortran_record(&model.harness_dir) {
                Some(objects) => {
                    model
                        .facts
                        .insert("fortran_objects".to_owned(), json!(objects.len()));
                    model.rebuilt_objects = objects;
                }
                None => model.warnings.push(format!(
                    "the harness has no {FORTRAN_BUILD_RECORD} (built by an older bhf), so the \
                     capsule links its Fortran objects as they were built instead of \
                     compiling them from source"
                )),
            }
        }
    }
    Ok(())
}

/// The objects `fortran-build.json` records, as build.sh compiles them: the
/// recorded flags without coverage instrumentation (a replay needs none),
/// module files in `obj/`.
fn read_fortran_record(harness_dir: &std::path::Path) -> Option<Vec<RebuiltObject>> {
    let bytes = std::fs::read(harness_dir.join(FORTRAN_BUILD_RECORD)).ok()?;
    let record: Value = serde_json::from_slice(&bytes).ok()?;
    if record.get("schema_version").and_then(Value::as_u64) != Some(1) {
        return None;
    }
    let objects = record.get("objects")?.as_array()?;
    let mut rebuilt = Vec::new();
    for object in objects {
        let path = PathBuf::from(object.get("object")?.as_str()?);
        let source = PathBuf::from(object.get("source")?.as_str()?);
        let mut flags: Vec<String> = object
            .get("flags")?
            .as_array()?
            .iter()
            .filter_map(Value::as_str)
            .filter(|flag| !flag.starts_with("-fsanitize-coverage"))
            .map(str::to_owned)
            .collect();
        flags.extend(["-J", "obj", "-I", "obj"].map(str::to_owned));
        rebuilt.push(RebuiltObject {
            object: path,
            source,
            compiler_var: "FC",
            flags,
        });
    }
    Some(rebuilt)
}

/// A crash the language runtime reported itself: libcob's runtime check
/// (`libcob: parseit.cob:11: error: offset of 'BUF' out of bounds: 200,
/// maximum: 8` is `COBOL:offset of 'BUF' out of bounds`).
pub(crate) fn runtime_signature(glue: Glue, stderr: &str) -> Option<String> {
    match glue {
        Glue::Cobol => stderr.lines().find_map(|line| {
            let rest = line.trim().strip_prefix("libcob: ")?;
            let (_, what) = rest.split_once("error: ")?;
            let what = what.split(':').next().unwrap_or(what).trim();
            (!what.is_empty()).then(|| format!("COBOL:{what}"))
        }),
        Glue::Fortran => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_libcob_check_is_the_cobol_signature() {
        let stderr = "libcob: /t/src/parseit.cob:11: error: offset of 'BUF' out of bounds: 200, maximum: 8\n\n\
                      /t/src/parseit.cob:11: attempt to reference unallocated memory (signal SIGSEGV)\n";
        assert_eq!(
            runtime_signature(Glue::Cobol, stderr).as_deref(),
            Some("COBOL:offset of 'BUF' out of bounds")
        );
        assert_eq!(runtime_signature(Glue::Cobol, "all fine\n"), None);
        assert_eq!(runtime_signature(Glue::Fortran, stderr), None);
    }

    /// The recorded Fortran objects compile without coverage, with module
    /// files in the capsule's object dir.
    #[test]
    fn the_fortran_record_is_read_without_coverage_flags() {
        let temp = tempfile::tempdir().unwrap();
        std::fs::write(
            temp.path().join(FORTRAN_BUILD_RECORD),
            json!({
                "schema_version": 1,
                "objects": [{
                    "object": "/w/h/fortran_target.o",
                    "source": "/t/parse.f90",
                    "flags": ["-O1", "-g", "-fsanitize=address",
                              "-fsanitize-coverage=trace-pc,trace-cmp", "-cpp"],
                }],
            })
            .to_string(),
        )
        .unwrap();
        let objects = read_fortran_record(temp.path()).unwrap();
        assert_eq!(objects.len(), 1);
        assert_eq!(objects[0].source, PathBuf::from("/t/parse.f90"));
        assert_eq!(
            objects[0].flags,
            [
                "-O1",
                "-g",
                "-fsanitize=address",
                "-cpp",
                "-J",
                "obj",
                "-I",
                "obj"
            ]
        );
    }
}
